<#
.SYNOPSIS
    WO-184: synthetic test for the joiner's saves, the mod's half (the three switches, mp_save_status, the line on screen, the snapshot bind). No game, relay or agent needed.
.DESCRIPTION
    Same driver as Test-NpcSmoothSynthetic.ps1 (the real kdcmp.lua under
    MoonSharp, engine stubbed, fake clock); scenario file
    Test-WO184Synthetic.lua. Evidence: docs/WO-184-findings.md.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\Test-WO184Synthetic.ps1
#>
[CmdletBinding()]
param(
    [string] $KdcmpLua = '',
    [string] $MoonSharpVersion = '2.0.0.0'
)
$toolsDir = Split-Path -Parent $MyInvocation.MyCommand.Path
& (Join-Path $toolsDir 'Test-NpcSmoothSynthetic.ps1') `
    -KdcmpLua $KdcmpLua -MoonSharpVersion $MoonSharpVersion `
    -Scenario (Join-Path $toolsDir 'Test-WO184Synthetic.lua') `
    -Title 'WO-184 synthetic game-side Lua test'
exit $LASTEXITCODE
