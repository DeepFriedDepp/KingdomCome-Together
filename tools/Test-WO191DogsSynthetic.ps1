<#
.SYNOPSIS
    The WO-191 follow-up: synthetic test for village dogs in the NPC stream (mp_dog_sync). No game, relay or agent needed.
.DESCRIPTION
    Same driver as Test-NpcSmoothSynthetic.ps1 (the real kdcmp.lua under
    MoonSharp, engine stubbed, fake clock); scenario file
    Test-WO191DogsSynthetic.lua. Evidence: docs/WO-191-dogs-findings.md.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\Test-WO191DogsSynthetic.ps1
#>
[CmdletBinding()]
param(
    [string] $KdcmpLua = '',
    [string] $MoonSharpVersion = '2.0.0.0'
)
$toolsDir = Split-Path -Parent $MyInvocation.MyCommand.Path
& (Join-Path $toolsDir 'Test-NpcSmoothSynthetic.ps1') `
    -KdcmpLua $KdcmpLua -MoonSharpVersion $MoonSharpVersion `
    -Scenario (Join-Path $toolsDir 'Test-WO191DogsSynthetic.lua') `
    -Title 'WO-191 follow-up (village dogs) synthetic game-side Lua test'
exit $LASTEXITCODE
