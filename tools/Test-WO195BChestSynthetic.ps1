<#
.SYNOPSIS
    WO-195B 2a: synthetic test of a joiner's unlocked chest unlocking the host's (the DoorAsk chest bit, mp_chest_sync).
    No game, relay or agent needed.
.DESCRIPTION
    Same driver as Test-NpcSmoothSynthetic.ps1 (the real kdcmp.lua under
    MoonSharp, engine stubbed, fake clock); scenario file
    Test-WO195BChestSynthetic.lua.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\Test-WO195BChestSynthetic.ps1
#>
[CmdletBinding()]
param(
    [string] $KdcmpLua = '',
    [string] $MoonSharpVersion = '2.0.0.0'
)
$toolsDir = Split-Path -Parent $MyInvocation.MyCommand.Path
& (Join-Path $toolsDir 'Test-NpcSmoothSynthetic.ps1') `
    -KdcmpLua $KdcmpLua -MoonSharpVersion $MoonSharpVersion `
    -Scenario (Join-Path $toolsDir 'Test-WO195BChestSynthetic.lua') `
    -Title 'WO-195B 2a chest unlock synthetic Lua test'
exit $LASTEXITCODE
