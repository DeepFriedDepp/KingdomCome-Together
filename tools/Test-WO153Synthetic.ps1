<#
.SYNOPSIS
    WO-153: synthetic test for the Lua half of the 0.43.0 tutorial-session fixes. No game, relay or agent needed.
.DESCRIPTION
    Same driver as Test-NpcSmoothSynthetic.ps1 (the real kdcmp.lua under
    MoonSharp, engine stubbed, fake clock); scenario file
    Test-WO153Synthetic.lua. Live evidence: docs/WO-153-findings.md.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\Test-WO153Synthetic.ps1
#>
[CmdletBinding()]
param(
    [string] $KdcmpLua = '',
    [string] $MoonSharpVersion = '2.0.0.0'
)
$toolsDir = Split-Path -Parent $MyInvocation.MyCommand.Path
& (Join-Path $toolsDir 'Test-NpcSmoothSynthetic.ps1') `
    -KdcmpLua $KdcmpLua -MoonSharpVersion $MoonSharpVersion `
    -Scenario (Join-Path $toolsDir 'Test-WO153Synthetic.lua') `
    -Title 'WO-153 synthetic tutorial-session fixes Lua test'
exit $LASTEXITCODE
