<#
.SYNOPSIS
    WO-191: synthetic test for the hotfix, the mod's half (the four switches, the fight guard on every sweep trigger, the attacker pin). No game, relay or agent needed.
.DESCRIPTION
    Same driver as Test-NpcSmoothSynthetic.ps1 (the real kdcmp.lua under
    MoonSharp, engine stubbed, fake clock); scenario file
    Test-WO191Synthetic.lua. Evidence: docs/WO-191-findings.md.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\Test-WO184Synthetic.ps1
#>
[CmdletBinding()]
param(
    [string] $KdcmpLua = '',
    [string] $MoonSharpVersion = '2.0.0.0'
)
$toolsDir = Split-Path -Parent $MyInvocation.MyCommand.Path
& (Join-Path $toolsDir 'Test-NpcSmoothSynthetic.ps1') `
    -KdcmpLua $KdcmpLua -MoonSharpVersion $MoonSharpVersion `
    -Scenario (Join-Path $toolsDir 'Test-WO191Synthetic.lua') `
    -Title 'WO-191 synthetic game-side Lua test'
exit $LASTEXITCODE
