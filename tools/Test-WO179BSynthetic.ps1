<#
.SYNOPSIS
    WO-179B: synthetic test for the shared video's Lua half (the switches, the copy's hold and skip check, a move that is no input, the length fallback, the ignore window's animals, the host's protection of a watching figure). No game, relay or agent needed.
.DESCRIPTION
    Same driver as Test-NpcSmoothSynthetic.ps1 (the real kdcmp.lua under
    MoonSharp, engine stubbed, fake clock); scenario file
    Test-WO179BSynthetic.lua. Live evidence: the work order's live checks.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\Test-WO179BSynthetic.ps1
#>
[CmdletBinding()]
param(
    [string] $KdcmpLua = '',
    [string] $MoonSharpVersion = '2.0.0.0'
)
$toolsDir = Split-Path -Parent $MyInvocation.MyCommand.Path
& (Join-Path $toolsDir 'Test-NpcSmoothSynthetic.ps1') `
    -KdcmpLua $KdcmpLua -MoonSharpVersion $MoonSharpVersion `
    -Scenario (Join-Path $toolsDir 'Test-WO179BSynthetic.lua') `
    -Title 'WO-179B synthetic game-side Lua test'
exit $LASTEXITCODE
