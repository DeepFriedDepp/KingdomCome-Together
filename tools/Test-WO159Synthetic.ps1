<#
.SYNOPSIS
    WO-159: synthetic test for the Lua half (the main menu: Start Game / Join Game). No game,
    relay or agent needed.
.DESCRIPTION
    Same driver as Test-NpcSmoothSynthetic.ps1 (the real kdcmp.lua under
    MoonSharp, engine stubbed, fake clock); scenario file
    Test-WO159Synthetic.lua. Live evidence: the WO-159 notes.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\Test-WO159Synthetic.ps1
#>
[CmdletBinding()]
param(
    [string] $KdcmpLua = '',
    [string] $MoonSharpVersion = '2.0.0.0'
)
$toolsDir = Split-Path -Parent $MyInvocation.MyCommand.Path
& (Join-Path $toolsDir 'Test-NpcSmoothSynthetic.ps1') `
    -KdcmpLua $KdcmpLua -MoonSharpVersion $MoonSharpVersion `
    -Scenario (Join-Path $toolsDir 'Test-WO159Synthetic.lua') `
    -Title 'WO-159 synthetic game-side Lua test'
exit $LASTEXITCODE
