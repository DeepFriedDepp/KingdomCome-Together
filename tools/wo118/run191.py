def say(*a): print(time.strftime('%H:%M:%S'), *a, flush=True)


def record(step, **kw):
    kw.update(step=step, at=time.strftime('%H:%M:%S'))
    open(RESULTS, 'a').write(json.dumps(kw) + '\n')
    print(json.dumps(kw, indent=1))


def lines_from(path, n0):
    with open(path, encoding='utf-8', errors='replace') as f:
        return f.read().splitlines()[n0:]


def nlines(path):
    with open(path, encoding='utf-8', errors='replace') as f:
        return sum(1 for _ in f)


def klines(off):
    with open(live.KLOG, 'rb') as f:
        f.seek(off); return f.read().decode('utf-8', 'replace').splitlines()


def place_beside(npc, gx, gy):
    for _ in range(2):
        live.lua("local e = System.GetEntityByName('%s'); if e then e:SetWorldPos({x=%f, y=%f, z=%f}) end" % (npc, gx - 1.4, gy, S.ground(gx - 1.4, gy) + 0.2))
        time.sleep(0.6)


def count(ls, needle): return sum(1 for l in ls if needle in l)


def nudge(seconds=9):
    """The agent takes the log-tail transport only when state frames come, and they come on movement (else it falls back to HTTP)."""
    for i in range(seconds):
        live.lua('local p = player:GetWorldPos(); player:SetWorldPos({x = p.x + %s, y = p.y, z = p.z + 0.2})' % ('0.3' if i % 2 == 0 else '-0.3'))
        time.sleep(1.0)


# ================================================================ L1: a relaunched joiner's swings are never stale

def l1(npc='ttkc_man_3', blows=6, every=2.5):
    R.stop('peer'); R.stop('agent'); time.sleep(6)
    R.relay(RELAY)
    g = S.ent_pos(npc)
    if not g: raise SystemExit('no npc ' + npc)
    hx, hy = g[0] - 30.0, g[1]
    for _ in range(3):
        live.lua('player:SetWorldPos({x=%f, y=%f, z=%f})' % (hx, hy, S.ground(hx, hy) + 0.3)); time.sleep(1.5)
    R.agent('w191l1', AGENT, [])                         # first: id 0, the host
    time.sleep(1)
    live.lua('local p = player:GetWorldPos(); player:SetWorldPos({x = p.x + 0.5, y = p.y, z = p.z + 0.2})')
    time.sleep(12)
    agentlog = R.load_state()['agentlog']
    gx, gy = g[0] + 1.6, g[1]
    gz = S.ground(gx, gy)
    t0 = 15
    total = int(t0 + blows * every + 15)
    plan = os.path.join(live.LOGS, 'plan.run191.l1.txt')
    open(plan, 'w').write('\n'.join([
        '# WO-191 L1 (generated by run191.py): host role; the synthetic joiner\'s figure beside %s, swings with hits' % npc, 'start 3',
        'ghost %.2f %.2f %.2f 0 1 50 0.0005 30' % (gx, gy, gz), 'gcombat 5 %d 1' % total,
        'jhit %d %s %s 450 6.0 15.0 %.2f %d' % (t0, npc, PUNCH, every, blows)]) + '\n')
    runs = []
    for run in ('a', 'b'):
        n0 = nlines(agentlog)
        R.peer('w191l1' + run, plan, ['--duration', str(total + 20)])
        start = time.time()
        time.sleep(max(0.0, start + 3 + t0 - 4 - time.time()))
        place_beside(npc, gx, gy)
        time.sleep(max(0.0, start + 3 + total - time.time()))
        R.stop('peer')                                   # the joiner's game (agent) goes away: a relaunch follows
        time.sleep(10)
        ag = lines_from(agentlog, n0)
        accepted = [l for l in ag if 'MP-ACTION section=inbound ghost=1 kind=Attack' in l]
        w173 = [l for l in ag if 'MP-W173 hit npc=' in l]
        runs.append({'run': run, 'attack_accepted': len(accepted), 'seqs': [m.group(1) for l in accepted for m in [re.search(r'seq=(\d+)', l)] if m],
                     'stale': count(ag, 'reject=StaleOrDuplicate'), 'wo191_action': [l[13:200] for l in ag if 'WO191-ACTION' in l][:6],
                     'w173_hits': len(w173), 'w173_no_swing_row': count(w173, 'fallback=no-swing-row'),
                     'w173_sample': [l[13:220] for l in w173[:2]], 'peers': [l[13:120] for l in ag if 'MP-PEERS ghost 1' in l]})
    ok = all(r['stale'] == 0 and r['attack_accepted'] == blows and r['w173_no_swing_row'] == 0 for r in runs)
    record('l1', ok=ok, npc=npc, blows=blows, runs=runs)
    R.stop('agent')
    return ok


# ================================================================ L2: no sweep while the copy fights (joiner role)

def l2(npc='ttkc_man_3'):
    R.stop('peer'); R.stop('agent'); time.sleep(6)
    R.relay(RELAY)
    g = S.ent_pos(npc)
    if not g: raise SystemExit('no npc ' + npc)
    # the copy 2 m in front of Henry (+x), Henry facing +x
    hx, hy = g[0] - 2.0, g[1]
    hz = S.ground(hx, hy)
    for _ in range(3):
        live.lua('player:SetWorldPos({x=%f, y=%f, z=%f}); player:SetWorldAngles({x=0, y=0, z=-1.5708})' % (hx, hy, hz + 0.3)); time.sleep(1.2)
    nz = S.ground(g[0], g[1])
    calm, fight = 40, 60
    plan = os.path.join(live.LOGS, 'plan.run191.l2.txt')
    open(plan, 'w').write('\n'.join([
        '# WO-191 L2 (generated by run191.py): joiner role; the host\'s copy of %s 2 m in front of this Henry' % npc, 'start 2',
        'hold %s %.2f %.2f %.2f 1.5708' % (npc, g[0], g[1], nz),
        'ncombat %d %d %s avatar:1' % (calm, calm + fight, npc)]) + '\n')
    R.peer('w191l2', plan, ['--duration', str(calm + fight + 40), '--claim-host'])   # first: id 0, the host
    time.sleep(2)
    koff = os.path.getsize(live.KLOG)
    R.agent('w191l2', AGENT, ['KCDMP_TEST_JOINER_IN_WORLD=1'])
    agentlog = R.load_state()['agentlog']
    start = time.time()
    marks = {}
    while time.time() - start < calm + fight + 25:
        # keep Henry facing the copy (its stream may move it a little)
        e = S.ent_pos(npc)
        if e:
            live.lua('player:SetWorldAngles({x=0, y=0, z=%f})' % (__import__('math').atan2(-(e[0] - hx), (e[1] - hy))))
        el = time.time() - start
        if 'fight_start' not in marks and el >= calm: marks['fight_start'] = os.path.getsize(live.KLOG)
        if 'fight_end' not in marks and el >= calm + fight: marks['fight_end'] = os.path.getsize(live.KLOG)
        time.sleep(1.0)
    calm_lines = []
    with open(live.KLOG, 'rb') as f:
        f.seek(koff); calm_lines = f.read(marks.get('fight_start', koff) - koff).decode('utf-8', 'replace').splitlines()
        f.seek(marks.get('fight_start', koff)); fight_lines = f.read(marks.get('fight_end', koff) - marks.get('fight_start', koff)).decode('utf-8', 'replace').splitlines()
    sw_calm = [l for l in calm_lines if 'WO164-SWEEP-LUA npc=%s' % npc in l]
    sw_fight = [l for l in fight_lines if 'WO164-SWEEP-LUA npc=%s' % npc in l]
    skip_fight = [l for l in fight_lines if 'WO191-SWEEP-LUA npc=%s' % npc in l]
    ag = lines_from(agentlog, 0)
    res = {'npc': npc, 'calm_sweeps': [l[:160] for l in sw_calm], 'fight_sweeps': [l[:160] for l in sw_fight], 'fight_skips_told': [l[:200] for l in skip_fight],
           'agent_skips': [l[13:200] for l in ag if 'WO191-SWEEP npc=' in l][:4], 'npc_combat_in': count(ag, 'MP-W132 npc-combat in') + count(ag, 'in a fight (the host'),
           'puppet': any(('puppet %s' % npc) in l for l in ag)}
    ok = len(sw_fight) == 0 and len(skip_fight) >= 1
    record('l2', ok=ok, calm_sweep_seen=len(sw_calm) > 0, **res)
    R.stop('agent'); R.stop('peer')
    return ok


# ================================================================ L3: an attacker that is not streamed is pinned at once (host role)

def l3(npc=None):
    """Asks the pin directly with the engine line's own path (Wo191OnEngineLine -> KCD2MP_W191PinTrack) for a dog the scan does not
    carry, with a synthetic joiner connected: the joiner's peer log must show the NPC's stream after it."""
    R.stop('peer'); R.stop('agent'); time.sleep(6)
    R.relay(RELAY)
    R.agent('w191l3', AGENT, ['KCDMP_TEST_W191=1'])
    nudge()
    time.sleep(3)
    # a living body of class Dog (or any class the scan misses) within 60 m of Henry
    live.lua('local p = player:GetWorldPos(); local out = {}; for _, e in ipairs(System.GetEntitiesInSphere(p, 80) or {}) do '
             'if e.class == "Dog" then out[#out + 1] = e:GetName() end end; System.LogAlways("W191DOGS " .. table.concat(out, ","))')
    time.sleep(1)
    dogs = [l for l in live.tail(live.KLOG, 3000) if l.startswith('W191DOGS')]
    names = [n for n in (dogs[-1][9:].split(',') if dogs else []) if n]
    say('dogs near Henry:', names)
    target = npc or (names[0] if names else None)
    if not target: record('l3', ok=False, why='no class-Dog body near Henry'); return False
    g = S.ent_pos(target)
    plan = os.path.join(live.LOGS, 'plan.run191.l3.txt')
    open(plan, 'w').write('\n'.join(['# WO-191 L3: a synthetic joiner beside %s' % target, 'start 2',
                                     'ghost %.2f %.2f %.2f 0 1 50 0.0005 30' % (g[0] + 3, g[1], S.ground(g[0] + 3, g[1]))]) + '\n')
    R.peer('w191l3', plan, ['--duration', '60'])
    time.sleep(8)
    koff = os.path.getsize(live.KLOG)
    agentlog = R.load_state()['agentlog']
    a0 = nlines(agentlog)
    tracked_before = live.lua('System.LogAlways("W191TRK " .. tostring(KCD2MP.npcTracked["%s"] ~= nil))' % target)
    time.sleep(0.5)
    before = [l for l in live.tail(live.KLOG, 3000) if l.startswith('W191TRK')]
    # the engine's own words, as the host's log tail delivers them: the agent's handler is fed the line by the mod's echo
    live.lua('KCD2MP_EmitEvent("w191_test", "target %s 1")' % target)
    time.sleep(6)
    kl = klines(koff)
    peerlog = R.load_state()['peerlog']
    plines = open(peerlog, encoding='utf-8', errors='replace').read().splitlines()
    res = {'npc': target, 'tracked_before': before[-1] if before else '?',
           'pinned': [l[:200] for l in kl if 'WO191-BIND' in l][:3], 'tracking': [l[:120] for l in kl if ('NPC-SYNC tracking ' + target) in l][:2],
           'agent': [l[13:200] for l in lines_from(agentlog, a0) if 'WO191' in l][:4],
           'peer_saw_stream': sum(1 for l in plines if target in l)}
    ok = bool(res['pinned']) and bool(res['tracking'])
    record('l3', ok=ok, **res)
    R.stop('peer'); R.stop('agent')
    return ok


# ================================================================ L3b: the joiner's side of an attacking animal

BITE = 'cfbf9094-9ba5-312a-b1a2-bcda0c23396a'   # the field's dog bite row (CombatAttackSyncGen attackFront+bite)


def l3b(streamed='ttkc_dog_1', bare='ttkc_dog_2'):
    """Joiner role. The synthetic host streams <streamed> 2.5 m from Henry and has it bite Henry (rows + hit verdicts): its copy exists and
    plays the bites. <bare> bites with no stream at all: the joiner asks for its body (WO191-BIND ask) and counts the blow (WO191-GHOST)."""
    R.stop('peer'); R.stop('agent'); time.sleep(6)
    R.relay(RELAY)
    p = henry()
    hx, hy = p[0], p[1]
    dz = S.ground(hx + 2.5, hy)
    plan = os.path.join(live.LOGS, 'plan.run191.l3b.txt')
    L = ['# WO-191 L3b: a dog that bites this Henry (streamed) and one that is not streamed', 'start 2',
         'hold %s %.2f %.2f %.2f -1.5708' % (streamed, hx + 2.5, hy, dz),
         'ncombat 8 60 %s avatar:1' % streamed]
    for i, t in enumerate((20, 24, 28)):
        L.append('row %d %s %s' % (t, streamed, BITE))
        L.append('verdict %.1f hit 1.0 2.0 %s 0 1 hid=%d' % (t + 1.2, streamed, 900 + i))
    for i, t in enumerate((40, 44)):
        L.append('row %d %s %s' % (t, bare, BITE))
        L.append('verdict %.1f hit 1.0 2.0 %s 0 1 hid=%d' % (t + 1.2, bare, 950 + i))
    open(plan, 'w').write('\n'.join(L) + '\n')
    R.peer('w191l3b', plan, ['--duration', '70', '--claim-host'])
    time.sleep(2)
    R.agent('w191l3b', AGENT, ['KCDMP_TEST_JOINER_IN_WORLD=1'])
    agentlog = R.load_state()['agentlog']
    nudge()
    time.sleep(62)
    ag = lines_from(agentlog, 0)
    res = {'puppet': [l[13:120] for l in ag if ('puppet %s' % streamed) in l][:1],
           'rows_streamed': [l[13:200] for l in ag if 'kind=NpcAttack npc=%s' % streamed in l or ('NpcAttack' in l and streamed in l)][:3],
           'hits_streamed': [l[13:220] for l in ag if 'WO161-HIT victim=me by=%s' % streamed in l][:3],
           'rows_bare': [l[13:160] for l in ag if 'kind=NpcAttack npc=%s' % bare in l][:2],
           'ask': [l[13:160] for l in ag if 'WO191-BIND ask npc=%s' % bare in l][:2],
           'ghost': [l[13:200] for l in ag if 'WO191-GHOST by=%s' % bare in l][:2]}
    ok = bool(res['puppet']) and all('no-entity' not in l for l in res['rows_streamed']) and bool(res['ask']) and bool(res['ghost'])         and not any('WO191-GHOST by=%s' % streamed in l for l in ag)
    record('l3b', ok=ok, **res)
    R.stop('agent'); R.stop('peer')
    return ok


def henry():
    r = S.ask('local p = player:GetWorldPos(); System.LogAlways(string.format("@TAG %.2f %.2f %.2f", p.x, p.y, p.z))', 'hp%d' % time.time_ns())
    return tuple(map(float, r.split()))


