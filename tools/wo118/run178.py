"""WO-178 C1/C2 live harness (never shipped; from WO-176 B2's): the joiner's lock-on onto an enemy copy and his own block.

Joiner role (KCDMP_TEST_JOINER_IN_WORLD=1) against a synthetic host: one armed copy (a longsword in hand) circling the player, its
swing rows every <every> s with the host's verdict at the row's own hit time; mp_victim_decides on. The player's own input under
the maintainer's input policy (tools/dev-input/game_input.py: the game window only, foreground-checked before every event, logged):
  none     nothing after the draw (key 1)
  block    the block button (right) pressed at the copy's striking-window start, held 1.4 s (through the hit)
  perfect  the block button pressed shortly before the row's own hit time (window start + hit - lead), released 0.25 s later
The swing's window start is the DLL's own line (WO166-STRIKE npc=<copy> window=N begin ...), tailed from the native log.

usage:
  python run178.py <agent.dll> <case> [swings] [every_s] [lead_ms]
W178_LOCK=on|off (mp_joiner_lock), W176_PAIR=0 by default here (no explicit hostile pair: any lock is the hostility answer's).
At the middle of every striking window the player's combat model is read (opp=); the copy's id is the agent's MP-W178 offer line.
Writes logs/run178.<tag>.json.
"""
import json, os, re, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'dev-input'))
import live
import run165 as R
import game_input as gi

PLAIN = 'ebf29add-635b-33d1-a908-ec7a052916d5'   # longsword stab, heavy: attack_time_to_start 0.533 + attack_time_to_hit 0.7
HIT_AFTER_BEGIN_MS = 700                          # the window begins at the row's start + time_to_start; the blow lands time_to_hit later
SWORD = '00cca9e3-8ef2-46db-8cbf-86ec51930919'
COPY = 'prepadeniNaCeste_bandit_7'                # a host road-event bandit: a stand-in body on this joiner (WO-167)
CX, CY = 2343.80, 2049.14
COPY_Z = 108.7   # set from the ground at the copy's spot before the plan is written
DIST = float(os.environ.get('W178_DIST', '2.2'))   # the copy's distance in front of the player (W178_DIST; the stab's contact reach is ~2.0 m)
RING = '2.6 0.000 108.71 108.76 108.66 108.55 108.32 108.35 108.31 108.19 108.04 108.06 108.26 108.60'


def stamp():
    return time.strftime('%H:%M:%S')


def plan(swings, every, t0=28.0, b3=False):
    end = t0 + swings * every + 20
    L = ['# WO-176 B2 joiner role (generated by run176b2.py)', 'start 10', 'ghost 2349.80 2049.14 109.08 0 1 2 0.0005 30', 'qmode 1 on',
         'hold %s %.2f %.2f %.2f 3.14159 drawn' % (COPY, CX, CY + DIST, COPY_Z), 'ncombat 0 %d %s avatar:1 3 1 0 3' % (int(end + 60), COPY),
         'hands 12 %s - %s' % (COPY, '-' if os.environ.get('W178_UNARMED') == '1' else SWORD)]
    rows = [r for r in os.environ.get('W178_ROWS', PLAIN).split(',') if r]   # W178_ROWS: the swing rows, cycled (e.g. the game's unarmed punches)
    for k in range(swings):
        v = os.environ.get('W176_VERDICT', 'hit')
        if v == 'alt': v = ('blocked', 'pb')[k % 2]
        L.append('swingat %.1f %s local %s 1233 %s 10 25' % (t0 + k * every, COPY, rows[k % len(rows)], v))
        if b3:   # B3a: the host's verdict on the joiner's own blow at this copy, no host reaction (react 0): the copy shows its own block row
            L.append('w164 %.1f 7 %s %s 0 e 0.0 12.0' % (t0 + k * every + 2.4, COPY, ('blocked', 'pb', 'broken')[k % 3]))
    return L, end


def run(agent_dll, case, swings=20, every=4.0, lead_ms=150, tag=None):
    tag = tag or os.environ.get('W178_TAG', 'c.%s' % case)
    R.stop('agent'); R.stop('peer')
    time.sleep(4)
    z = None
    live.lua('System.LogAlways("[W176G] " .. tostring(System.GetTerrainElevation({x=%f, y=%f, z=0})))' % (CX, CY))
    time.sleep(0.4)
    for l in reversed(live.tail(live.KLOG, 20, r'\[W176G\]')):
        z = float(l.split('[W176G] ')[1]); break
    for _ in range(3):
        live.lua('player:SetWorldPos({x=%f, y=%f, z=%f}); player:SetWorldAngles({x=0, y=0, z=0})' % (CX, CY, (z or 108.7) + 0.3)); time.sleep(1.0)
    global COPY_Z
    live.lua('System.LogAlways("[W176G] " .. tostring(System.GetTerrainElevation({x=%f, y=%f, z=0})))' % (CX, CY + DIST))
    time.sleep(0.4)
    for l in reversed(live.tail(live.KLOG, 20, r'\[W176G\]')):
        COPY_Z = float(l.split('[W176G] ')[1]); break
    L, end = plan(swings, every, b3=(case == 'none' and os.environ.get('W176_B3A', '1') == '1'))
    path = os.path.join(live.LOGS, 'plan.run178.%s.txt' % tag)
    open(path, 'w').write('\n'.join(L) + '\n')
    with open(live.NLOG, 'rb') as f:
        f.seek(0, 2); npos = f.tell()
    ag0 = 0
    R.peer('r178' + tag, path, ['--duration', str(int(end + 20)), '--claim-host'])
    t_peer = time.time()
    R.agent('r178' + tag, agent_dll, ['KCDMP_TEST_JOINER_IN_WORLD=1'])
    time.sleep(12)
    live.cmd('mp_leash off')
    live.cmd('mp_victim_decides %s' % os.environ.get('W176_VD', 'on'))
    live.cmd('mp_joiner_lock %s' % os.environ.get('W178_LOCK', 'on'))
    if os.environ.get('W178_TRACE'):
        live.cmd('mp_w178_trace %s' % os.environ['W178_TRACE'])   # the duel trace, once the agent is up (it goes through the agent)
    if os.environ.get('W176_PAIR', '0') == '1':
        live.cmd('mp_w163_probe pair %s on 1' % COPY)   # the explicit hostile pair: the engine's own opponent selector may pick the copy (WO-165 P6)
    # Henry topped up in-game (the harness's; the engine's own block / damage rules untouched): 20 unblocked stabs would kill him
    live.lua('W176KEEP = (W176KEEP or 0) + 1; local gen = W176KEEP; local function k() if gen ~= W176KEEP then return end; '
             'if player.soul:GetState("health") < 60 then player.soul:SetState("health", 100) end; Script.SetTimer(400, k) end; k()')
    # draw by the player's own key, then the case's input on each striking window
    if os.environ.get('W178_NOINPUT') == '1':   # the maintainer plays: nothing is sent, the window is never touched
        class _NoInput:
            sent = 0
            def front(self, *a): pass
            def back(self): pass
            def tap(self, *a): pass
            def button(self, *a): pass
            def release_all(self): pass
            def move(self, *a): pass
        g = _NoInput()
    else:
        g = gi.Game('wo178-%s' % tag)
    lockreads = []
    g.front()
    seen, shots, events = 0, [], []
    st0 = R.load_state()
    alog = st0['agentlog']
    apos = os.path.getsize(alog) if os.path.exists(alog) else 0
    try:
        g.tap('1', 120)
        time.sleep(2.5)
        pitch = int(os.environ.get('W178_PITCH', '0'))   # the camera up by this many mouse counts (the save's camera looks at the ground)
        for _ in range(abs(pitch) // 40):
            g.move(0, -40 if pitch > 0 else 40); time.sleep(0.03)
        if pitch:
            time.sleep(0.8); live.cmd('r_GetScreenShot 1'); shots.append('pitch')
        live.cmd('mp_w163_probe model me')
        deadline = t_peer + 10 + end
        buf = b''
        trig = ('MP-ACTION section=inbound kind=NpcAttack npc=%s ' % COPY).encode()
        while time.time() < deadline and seen < swings:
            with open(alog, 'rb') as f:
                f.seek(apos); chunk = f.read(); apos = f.tell()
            buf += chunk
            lines = buf.split(b'\n'); buf = lines[-1]
            for raw in lines[:-1]:
                if os.environ.get('W176_SHOTS') == 'rows' and len(shots) < 4:
                    for key, tagx in ((b'WO176-COPYBLOCK npc=', 'copyblock'), (b'WO165-RECOIL npc=', 'recoil')):
                        if key in raw and b'row="' in raw or (key in raw and b'recoil="' in raw):
                            if tagx not in [x for x in shots if isinstance(x, str)]:
                                time.sleep(0.35)
                                live.cmd('r_GetScreenShot 1')
                                shots.append(tagx); shots.append(stamp())
                if trig not in raw: continue
                t_row = time.time()          # the row starts on this machine as the agent writes this line
                seen += 1
                events.append({'n': seen, 'row_seen': stamp()})
                if case == 'block':
                    g.button('right', True)
                    time.sleep(1.9)
                    g.button('right', False)
                elif case == 'perfect':
                    pre = float(os.environ.get('W178_SHOT_PRE', '0'))   # a screenshot inside the shield's window, before the press
                    if pre > 0:
                        w0 = pre - (time.time() - t_row)
                        if w0 > 0: time.sleep(w0)
                        live.cmd('r_GetScreenShot 1'); shots.append('pre%d' % seen)
                    wait = (533 + HIT_AFTER_BEGIN_MS - lead_ms) / 1000.0 - (time.time() - t_row)
                    if wait > 0: time.sleep(wait)
                    g.button('right', True)
                    time.sleep(0.25)
                    g.button('right', False)
                    if os.environ.get('W178_COUNTER') == '1':   # the counter (riposte) right after the perfect block: the attack button
                        time.sleep(float(os.environ.get('W178_COUNTER_AFTER', '0.15')))
                        g.click('left', 80)
                        if os.environ.get('W178_SHOT_COUNTER') == '1':
                            live.cmd('r_GetScreenShot 1'); shots.append('counter%d' % seen)
                if os.environ.get('W178_REPOS') == '1':   # the player back on his spot after each swing (a recoil pushes him out of reach)
                    time.sleep(1.6)
                    live.lua('player:SetWorldPos({x=%f, y=%f, z=%f}); player:SetWorldAngles({x=0, y=0, z=0})' % (CX, CY, (z or 108.7) + 0.05))
                if case == 'none':   # C1: the lock at the striking window's middle (row start + 533 + ~350 ms)
                    mid = 0.88 - (time.time() - t_row)
                    if mid > 0: time.sleep(mid)
                    live.cmd('mp_w163_probe model me')
                    lockreads.append(stamp())
                if os.environ.get('W178_SHOTS', '1') == '1' and os.environ.get('W176_SHOTS') != 'rows':   # the game's own prompts at the striking window's middle, every swing
                    mid = float(os.environ.get('W178_SHOT_AT', '0.88')) - (time.time() - t_row)
                    if mid > 0: time.sleep(mid)
                    live.cmd('r_GetScreenShot 1')
                    shots.append(seen)
            time.sleep(0.01)
    except gi.NotFocused as e:
        events.append({'stopped': str(e)})
    finally:
        g.release_all()
        time.sleep(3.0)
        g.back()
    live.lua('W176KEEP = (W176KEEP or 0) + 1')
    live.cmd('mp_w178_status')
    time.sleep(4.0)
    with open(live.NLOG, 'rb') as f:
        f.seek(0)
        nat = f.read().decode('utf-8', 'replace').splitlines()
    st = R.load_state()
    ag = open(st['agentlog'], encoding='utf-8', errors='replace').read().splitlines() if st.get('agentlog') else []
    reps = [l for l in ag if l.startswith('WO165-REPLAY hid=')]
    res = {'tag': tag, 'case': case, 'windows_seen': seen, 'screens_at_swing': shots, 'replays': len(reps)}
    d = {}
    for l in reps:
        m = re.search(r'engine=(\S+)', l); d[m.group(1) if m else '?'] = d.get(m.group(1) if m else '?', 0) + 1
    res['engine'] = d
    fb = {}
    for l in reps:
        m = re.search(r'fallback=(\S+)', l); fb[m.group(1) if m else '?'] = fb.get(m.group(1) if m else '?', 0) + 1
    res['fallback'] = fb
    res['wo161_hit_applied'] = {k: sum(('applied=' + k) in l for l in ag if l.startswith('WO161-HIT')) for k in ('engine', 'yes', 'no', 'dup')}
    res['outcomes_sent'] = sum('W164' in l and 'hit-outcome' in l for l in ag)
    res['recoils'] = [l[:200] for l in ag if l.startswith('WO165-RECOIL')][:4]
    res['recoil_count'] = sum(l.startswith('WO165-RECOIL') and 'recoil="' in l for l in ag)
    res['copy_blocks'] = [l[:220] for l in ag if l.startswith('WO176-COPYBLOCK')][:6]
    res['copy_block_rows'] = sum(l.startswith('WO176-COPYBLOCK') and 'row="' in l for l in ag)
    res['native_replay_samples'] = [l.strip()[15:420] for l in nat if 'WO165-REPLAY seq=' in l][-3:]
    res['player_mid_states'] = [re.search(r'player_state=(\S+)', l).group(1) for l in nat if 'WO166-STRIKE npc=%s' % COPY in l and ' mid ' in l and 'player_state=' in l][-swings:]
    res['player_down'] = sum('WO155-FALL' in l or 'local down' in l for l in nat[-4000:])
    res['faults'] = [l.strip()[15:200] for l in nat[-6000:] if ('FAULT' in l and 'FAULT-SUM' not in l) or 'switched off' in l][:5]
    res['events'] = events[:3]
    res['model_me'] = [l[:260] for l in ag if 'WO163-PROBE model' in l][-2:]
    res['pair'] = [l[:200] for l in ag if 'WO163-PROBE pair' in l][-2:]
    offers = [l for l in ag if l.startswith('MP-W178 offer npc=%s ' % COPY)]
    m = re.search(r'eid=0x([0-9A-F]+)', offers[-1]) if offers else None
    ceid = int(m.group(1), 16) if m else None
    opps = [re.search(r'opp=0x([0-9A-F]+)', l) for l in ag if l.startswith('WO163-MODEL npc=me ')]
    opps = [int(x.group(1), 16) for x in opps if x]
    res['copy_eid'] = hex(ceid) if ceid else None
    res['lock_reads'] = len(opps)
    res['lock_on_copy'] = sum(1 for o in opps if ceid and o == ceid)
    res['lock_none'] = sum(1 for o in opps if o == 0)
    res['lock_other'] = len(opps) - res['lock_on_copy'] - res['lock_none']
    res['w178_stats'] = [l[:900] for l in ag if l.startswith('MP-W178-STATS')][-1:]
    res['w178_offers'] = [l[:200] for l in ag if l.startswith('MP-W178 offer')][:4]
    res['hostile_lines'] = [l.strip()[15:260] for l in nat if 'WO178-HOSTILE' in l][-6:]
    res['opponent_changes'] = [l.strip()[:200] for l in open(live.KLOG, encoding='utf-8', errors='replace').read().splitlines()[-6000:] if 'Opponent change' in l][-8:]
    json.dump(res, open(os.path.join(live.LOGS, 'run178.%s.json' % tag), 'w'), indent=1)
    R.stop('agent'); R.stop('peer')
    print(json.dumps(res, indent=1))
    return res


if __name__ == '__main__':
    a = sys.argv
    run(a[1], a[2], int(a[3]) if len(a) > 3 else 20, float(a[4]) if len(a) > 4 else 4.0, int(a[5]) if len(a) > 5 else 150)
