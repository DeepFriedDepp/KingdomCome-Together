def agent_lines(path, since, until):
    out = []
    with open(path, encoding='utf-8', errors='replace') as f:
        for l in f:
            if len(l) > 12 and l[2] == ':' and since <= l[:8] <= until: out.append(l)
    return out


def c1(agent_dll, guard, modes, secs):
    """C1 (host role): the synthetic joiner's figure, held in combat (gcombat), strikes a local guard (avatarfight: stamina only) so
    the guard fights it; per figure automation pattern (mp_w166_automode), the guard's committed attacks on it, the blows that land,
    and the figure's own committed actions (cap_ours)."""
    R.stop('agent'); R.stop('peer')
    time.sleep(7)
    g = S.ent_pos(guard)
    if not g: raise SystemExit('no guard ' + guard)
    gx, gy = g[0] + 1.6, g[1]
    gz = S.ground(gx, gy)
    # Henry 30 m away (no host lock-on, the guard never on Henry)
    hx, hy = g[0] - 30.0, g[1]
    hz = S.ground(hx, hy)
    for _ in range(3):
        live.lua('player:SetWorldPos({x=%f, y=%f, z=%f})' % (hx, hy, hz + 0.3)); time.sleep(1.5)
    total = len(modes) * secs + 120
    L = ['# WO-166 C1 (generated by run166.py): this machine is the HOST; the synthetic joiner\'s figure, in combat, strikes a local guard',
         'start 3', 'ghost %.2f %.2f %.2f 0 1 50 0.0005 30' % (gx, gy, gz), 'avatarfight 3 %d %s 2.0 0 3' % (total, guard),
         'gcombat 0 %d 1' % total]
    plan = os.path.join(live.LOGS, 'plan.run166.c1.txt')
    open(plan, 'w').write('\n'.join(L) + '\n')
    R.agent('r166c1', agent_dll, [])            # the agent first: in a shared world it claims host and is the authority
    time.sleep(10)
    R.peer('r166c1', plan, ['--duration', str(total + 60)])
    agentlog = R.load_state()['agentlog']
    time.sleep(25)
    res = {'guard': guard, 'secs': secs, 'modes': []}
    for m in modes:
        live.cmd('mp_w166_automode %d' % m)
        time.sleep(3)
        since = time.strftime('%H:%M:%S')
        time.sleep(secs)
        until = time.strftime('%H:%M:%S')
        nat = window_lines(live.NLOG, since, until)
        ag = agent_lines(agentlog, since, until)
        landed = sum(1 for l in nat if 'WO132-HITS npc hit on avatar' in l)
        rows = sum(1 for l in ag if 'MP-ACTION section=outbound kind=NpcAttack npc=%s ' % guard in l)
        autos = [l.split('WO121-MOTION ', 1)[1].strip()[:120] for l in nat if 'WO121-MOTION body=kcd2mp_' in l and 'combat automation' in l]
        stats = [l for l in ag if 'MP-WO121-STATS' in l]
        ours = re.findall(r'cap_ours=(\d+)', stats[-1]) if stats else []
        res['modes'].append({'mode': m, 'window': [since, until], 'guard_attack_rows': rows, 'blows_landed': landed,
                             'automation_lines': autos[-2:], 'cap_ours_end': int(ours[0]) if ours else None})
        print(json.dumps(res['modes'][-1]))
    live.cmd('mp_w166_automode 0')
    json.dump(res, open(os.path.join(live.LOGS, 'run166.c1.json'), 'w'), indent=1)


def r1s1(guard):
    """R1 + S1 (host role, the C1 run's agent and a new peer): the figure strikes the guard, the guard's blows land, the joiner dies and
    wakes (raw 0x23 / 0x3E); Henry then stands 200 m away while the figure fights on."""
