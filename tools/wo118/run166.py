ROW = '3e27732b-b152-4a27-97d2-1ebba717a588'   # the WO-165 plans' swing row (a catalogued attack with its own timings)
QPATH = 'Barbora.trosecko.kovar.hibernace.porovnani_kvality.kvalitaMece'


def c4_head():
    """The WO-165 C4 plan's head: the ghost and the three ring fighters with their combat state."""
    keep = []
    for l in open(os.path.join(live.HERE, 'plans', 'plan.wo165.c4.txt')):
        if l.startswith(('ghost ', 'fightz ', 'ncombat ')):
            if l.startswith('ncombat '):
                f = l.split(); f[2] = '99999'; l = ' '.join(f) + '\n'
            keep.append(l.rstrip('\n'))
    return keep


def plan_fight(tag, minutes):
    L = ['# WO-166 (generated by run166.py): joiner role, 3 copies round the player, a swing every 1.5 s, the host\'s weather, a checkpoint',
         'start 20'] + c4_head()
    npcs = ['ttkc_man_31', 'ttkc_man_30', 'ttkc_man_3']
    t, i = 20.0, 0
    end = 20 + minutes * 60
    while t < end:
        v = 'hit 0 1' if i % 2 == 0 else 'blocked 0 2'   # stamina only: a long run never kills the player (the life gate refuses while down)
        L.append('swingat %.1f %s local %s 220 %s' % (t, npcs[i % 3], ROW, v))
        t += 1.5; i += 1
    L += ['w164 25 5 0.62 semicloudy_clear_B', 'w164 %d 5 0.10 cloudy_no_rain' % min(end - 20, 140),
          'qcp 30 3 %s' % QPATH, 'qcp 75 3 %s' % QPATH]
    path = os.path.join(live.LOGS, 'plan.run166.%s.txt' % tag)
    open(path, 'w').write('\n'.join(L) + '\n')
    return path, i


def window_lines(path, since, until):
    out = []
    with open(path, encoding='utf-8', errors='replace') as f:
        for l in f:
            if l.startswith('[') and since <= l[1:9] <= until: out.append(l)
    return out


def fight(tag, agent_dll, minutes, delay, snap, strikes=''):
    R.stop('agent'); R.stop('peer')
    time.sleep(7)
    plan, nswings = plan_fight(tag, minutes)
    z = S.ground(2343.8, 2049.14)
    for _ in range(3):   # a long teleport lands before the ground's physics: held on the terrain until steady (kcd2-teleport-falls-through)
        live.lua('player:SetWorldPos({x=2343.8, y=2049.14, z=%f})' % (z + 0.3))
        time.sleep(1.5)
    opts = ['--duration', str(int(minutes * 60 + 40)), '--claim-host']
    if delay > 0: opts += ['--delay-ms', str(delay)]
    R.peer('r166' + tag, plan, opts)
    t_peer = time.time()
    R.agent('r166' + tag, agent_dll, ['KCDMP_TEST_JOINER_IN_WORLD=1'])
    time.sleep(12)
    live.cmd('mp_leash off')
    if snap in ('on', 'off'): live.cmd('mp_snap_fix ' + snap)
    if strikes in ('on', 'off'): live.cmd('mp_copy_strikes ' + strikes)
    time.sleep(max(0, t_peer + 20 - time.time()))
    since = time.strftime('%H:%M:%S')
    time.sleep(minutes * 60 + 4)
    live.cmd('mp_w166_status')
    time.sleep(62)   # the agent's minute lines (MP-WO166 native, MP-WO161-STATS)
    until = time.strftime('%H:%M:%S')
    st = R.load_state()
    agentlog = st['agentlog']
    native = os.path.join(live.LOGS, 'run166.%s.native.log' % tag)
    open(native, 'w', encoding='utf-8').writelines(window_lines(live.NLOG, since, until))
    a = open(agentlog, encoding='utf-8', errors='replace').read()
    res = {'tag': tag, 'minutes': minutes, 'delay_ms': delay, 'snap': snap, 'strikes': strikes or 'on', 'swings_planned': nswings, 'window': [since, until]}
    hits = re.findall(r'WO161-HIT victim=me .*', a)
    res['wo161_hits'] = len(hits)
    res['applied_dup'] = sum(1 for h in hits if 'applied=dup' in h)
    reasons = {}
    for h in hits:
        m = re.search(r'shown=(\w+) reason=([\w-]+)', h)
        if m: reasons[m.group(1) + ':' + m.group(2)] = reasons.get(m.group(1) + ':' + m.group(2), 0) + 1
    res['shown_reasons'] = reasons
    res['strike_lines'] = len(re.findall(r'WO166-STRIKE', a))
    nat = open(native, encoding='utf-8', errors='replace').read()
    res['strike_begin'] = len(re.findall(r'WO166-STRIKE npc=\S+ window=\d+ begin', nat))
    res['strike_mid_striking'] = len(re.findall(r'WO166-STRIKE npc=\S+ window=\d+ mid state=0x8 ', nat))
    res['strike_mid_lines'] = len(re.findall(r'WO166-STRIKE npc=\S+ window=\d+ mid ', nat))
    res['strike_player_opp_copy'] = len(re.findall(r'player_opponent=this-copy', nat))
    res['strike_end_prior_back'] = len(re.findall(r'end state_now=\S+ -> prior state back', nat))
    res['strike_switched_off'] = len(re.findall(r'WO166-STRIKE switched OFF', nat))
    res['localhit_dropped'] = len(re.findall(r'WO166-LOCALHIT dropped', nat))
    res['native_status'] = (re.findall(r'MP-WO166 native: (.*)', a) or [''])[-1][:600]
    res['qfix'] = re.findall(r'WO164-QFIX var=\S*kvalitaMece.*', a)[-3:]
    res['weather_agent'] = re.findall(r'WO166-WEATHER .*', a)[-3:]
    k = open(live.KLOG, encoding='utf-8', errors='replace').read()
    res['weather_lua'] = re.findall(r'WO166-WEATHER applied[^\n]*', k)[-3:]
    res['w166_status_lua'] = (re.findall(r'WO166-STATUS[^\n]*', k) or [''])[-1][:400]
    res['frame'] = [l[l.find('FRAME'):][:200] for l in nat.splitlines() if 'FRAME ' in l][-6:]
    out = subprocess.run([sys.executable, os.path.join(live.HERE, 'fightsnap165.py'), '--native', native, '--agent', agentlog], capture_output=True, text=True).stdout
    try:
        snapm = json.loads(out)
        res['fightsnap'] = {k2: snapm.get(k2) for k2 in ('fight', 'holds')}
    except Exception:
        res['fightsnap'] = out[:400]
    res['faults'] = len(re.findall(r'FAULT|switched OFF|faulted', nat))
    json.dump(res, open(os.path.join(live.LOGS, 'run166.%s.json' % tag), 'w'), indent=1)
    print(json.dumps(res, indent=1)[:6000])


def body_list(name):
    s = S.ask('local e=System.GetEntityByName("%s"); local t={}; if e and e.inventory then for _,w in ipairs(e.inventory:GetInventoryTable()) do local it=ItemManager.GetItem(w); if it then t[#t+1]=it.class end end end; table.sort(t); System.LogAlways("@TAG "..table.concat(t,","))' % name,
              'bl%d' % time.time_ns())
    return s or ''


def loot(n, corpse):
    """L1 in the game: the mod's own open path on a corpse copy, a host update while the game's loot screen is open, the close."""
    res = {'cycles': 0, 'deferred': 0, 'applied': 0, 'closed_by': {}, 'rewritten_under_screen': 0, 'crash': False}
    klen0 = S.klen()
    for i in range(n):
        before = body_list(corpse)
        # the joiner's loot request (BasicAIActions.OnLoot -> the W131 wrap -> W134LootRequest), then the host's answer
        live.lua('local e=System.GetEntityByName("%s"); if e then BasicAIActions.OnLoot(e, player, 1) end' % corpse)
        time.sleep(0.4)
        live.lua('KCD2MP_W134BodyState("%s", "open", 1, 1, 1, {{"b0fc8e19-af72-4771-9517-caec4f568920", 1, 1, false}, {"a856e87a-8065-4338-919d-0aff7a63341d", 1, 1, false}})' % corpse)
        time.sleep(1.2)
        opened = body_list(corpse)
        # the host looted the sword meanwhile: an update while the screen is open
        live.lua('KCD2MP_W134BodyState("%s", "update", 1, 1, 1, {{"a856e87a-8065-4338-919d-0aff7a63341d", 1, 1, false}})' % corpse)
        time.sleep(0.8)
        under = body_list(corpse)
        if under != opened: res['rewritten_under_screen'] += 1
        # the game's own close of the loot screen (its Flash element's Close; no key press)
        live.lua('UIAction.CallFunction("ItemTransfer", -1, "Close", true)')
        time.sleep(1.5)
        res['cycles'] += 1
        if not live.up(): res['crash'] = True; break
    time.sleep(2)
    lines = S.kcd_lines(r'WO166-LOOT (deferred|applied|listener)|ui_inv_screen_(in|out)', klen0)
    res['deferred'] = sum(1 for l in lines if 'WO166-LOOT deferred' in l)
    res['applied'] = sum(1 for l in lines if 'WO166-LOOT applied' in l)
    for l in lines:
        m = re.search(r'close=(\w+)', l)
        if m: res['closed_by'][m.group(1)] = res['closed_by'].get(m.group(1), 0) + 1
    res['screen_in'] = sum(1 for l in lines if 'ui_inv_screen_in' in l)
    res['screen_out'] = sum(1 for l in lines if 'ui_inv_screen_out' in l)
    res['listener'] = [l.strip()[:160] for l in lines if 'listener' in l][:2]
    res['game_up'] = live.up()
    json.dump(res, open(os.path.join(live.LOGS, 'run166.loot.json'), 'w'), indent=1)
    print(json.dumps(res, indent=1))


