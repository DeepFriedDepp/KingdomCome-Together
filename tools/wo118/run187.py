def front_or_wait(gi, g, secs=900):
    """The game to the front; when Windows refuses (the desktop app the maintainer is using keeps the foreground), wait -- sending
    nothing -- until the maintainer clicks the game window, then aim and settle. False = it never came to the front.
    W187_NO_FRONT=1: never pull the game over the maintainer's own window -- only wait for the click."""
    if os.environ.get('W187_NO_FRONT') != '1':
        g.front()
    if gi.foreground_is_game(g.pids):
        return True
    gi.log(g.test, 'front: refused by the window manager -- waiting (nothing sent) for the game window to be clicked')
    print(stamp(), 'WAITING: click the game window (nothing is sent until it is in front)', flush=True)
    t_end = time.time() + secs
    while time.time() < t_end:
        if gi.foreground_is_game(g.pids):
            time.sleep(3.0)
            if gi.foreground_is_game(g.pids):
                g.aim()
                gi.log(g.test, 'front: the game window is in front (clicked) -- input may start')
                print(stamp(), 'the game is in front: starting', flush=True)
                return True
        time.sleep(0.5)
    return False


