def vanilla(agent_dll, weapon='mace', secs=150, unblocked=4, lead_ms=None, g=None, blocked=4):
    """B3: the engine's own timeline of a mace (or bare-handed) attacker, single player, the duel trace on (read-only): the first
    `unblocked` swings taken (contact), then a perfect block at every wind-up, pressed `lead_ms` before the countdown the trace reads
    at the wind-up (= the row's attack_time_to_hit). run178's cases: the block held 1.9 s from the wind-up, the perfect tap 150 ms before
    contact (W187_LEAD_MS), released 0.25 s later."""
    gi = need_input()
    if lead_ms is None:
        lead_ms = int(os.environ.get('W187_LEAD_MS', '150'))
    tag = os.environ.get('W187_TAG', time.strftime('%H%M%S'))
    # the game in front (or the maintainer's click awaited) BEFORE anything starts: nobody attacks Henry while the harness waits
    own = g is None   # a sitting brings the game to the front once for all its cases
    if own:
        g = gi.Game('wo187-vanilla-%s' % tag)
        if not front_or_wait(gi, g, float(os.environ.get('W187_WAIT_S', '900'))):
            raise SystemExit('the game never came to the front: nothing was sent')
    R.stop('agent'); R.stop('peer')
    time.sleep(4)
    R.agent('r187v' + tag, agent_dll, [])   # the trace and the scope log go through the agent
    time.sleep(10)
    live.cmd('mp_anim_scope_log on')
    keep_up()
    live.lua('local p = player:GetWorldPos(); local yaw = player:GetWorldAngles().z; local x, y = p.x - math.sin(yaw) * 3, p.y + math.cos(yaw) * 3; '
             'local z = System.GetTerrainElevation({x=x, y=y, z=0}) or p.z; '
             'if not System.GetEntityByName("%s") then XGenAIModule.SpawnEntity({ Name = "%s", ClassName = "NPC", Pos = { x, y, z }, '
             'SharedSoulGuid = "%s", NoAI = false }) end; local e = System.GetEntityByName("%s"); '
             'if e then pcall(function() e:SetFlags(ENTITY_FLAG_NO_SAVE, 3) end) end' % (VNPC, VNPC, SOUL, VNPC))
    time.sleep(2)
    # the mace in the commoner's hand: equipped and drawn from the inventory (the mod's own mp_npc_draw route); equipped alone, the
    # commoner fought bare-handed (vs4: every wind-up wpn=12, the unarmed class)
    draw_mace = ('local e = System.GetEntityByName("%s"); if e then local ok, id = pcall(function() return e.inventory:FindItem("%s") end); '
                 'if ok and id then pcall(function() e.actor:EquipInventoryItem(id) end); pcall(function() e.human:DrawFromInventory(id, 0, true) end) end; '
                 'System.LogAlways("[W187V] mace drawn " .. tostring(ok and id ~= nil)) end' % (VNPC, MACE))
    if weapon == 'mace':
        live.lua('local e = System.GetEntityByName("%s"); if e then pcall(function() e.inventory:CreateItem("%s", 1, 1) end) end' % (VNPC, MACE))
        time.sleep(0.5)
        live.lua(draw_mace)
    time.sleep(1)
    attack = ('local e = System.GetEntityByName("%s"); if e then local t = XGenAIModule.MakeTableFromType("crime:attackInitiatedByConcept"); '
              't.target = player.this.id; t.priorityTarget = true; '
              'pcall(function() XGenAIModule.SendMessageToEntityData(e.this.id, "crime:attackInitiatedByConcept", t) end) end' % VNPC)
    live.lua(attack)
    live.cmd('mp_w178_trace %d' % min(600, int(secs) + 10))
    noff = size(live.NLOG)
    events, seen, last_state, pressed, redraws = [], 0, None, 0, 0
    t_end = time.time() + secs
    try:
        # Henry's sword drawn for the mace, holstered for the brawl (key 1 toggles: read the state first)
        if drawn() != (weapon == 'mace'):
            g.tap('1', 120); time.sleep(2.0)
        buf = b''
        last_attack = time.time()
        while time.time() < t_end:
            if time.time() - last_attack > 15:   # the attack interrupt again (a commoner may drift off)
                live.lua(attack); last_attack = time.time()
            with open(live.NLOG, 'rb') as f:
                f.seek(noff); chunk = f.read(); noff = f.tell()
            buf += chunk
            lines = buf.split(b'\n'); buf = lines[-1]
            for raw in lines[:-1]:
                m = TRACE.search(raw.decode('utf-8', 'replace'))
                if not m or m.group(3) != VNPC: continue
                st = int(m.group(4), 16)
                if st == 4 and last_state != 4:
                    seen += 1
                    cd = re.search(r'p5c0=[^:\s]*:(-?[0-9.]+)', m.group(5))
                    countdown = float(cd.group(1)) if cd else 0.8
                    wp = re.search(r'wpn=(-?[0-9]+)', m.group(5))
                    wpn = int(wp.group(1)) if wp else None
                    ev = {'n': seen, 'at': stamp(), 'countdown': countdown, 'pressed': False, 'case': 'none', 'wpn': wpn}
                    if weapon == 'mace' and wpn == 12 and redraws < 3:   # still bare-handed: draw the mace again
                        live.lua(draw_mace); redraws += 1; ev['redraw'] = True
                    if unblocked < seen <= unblocked + blocked:   # run178's 'block': held from the wind-up through the hit
                        g.button('right', True); time.sleep(1.9); g.button('right', False)
                        ev['case'] = 'block'
                    elif seen > unblocked + blocked and countdown > lead_ms / 1000.0:   # run178's 'perfect': a tap before contact
                        time.sleep(max(0.0, countdown - lead_ms / 1000.0))
                        g.button('right', True); time.sleep(0.25); g.button('right', False)
                        ev['pressed'] = True; pressed += 1; ev['case'] = 'perfect'
                    events.append(ev)
                last_state = st
            time.sleep(0.01)
    except gi.NotFocused as e:
        events.append({'stopped': str(e)})
    finally:
        g.release_all()
        time.sleep(1.0)
        if own: g.back()
        live.lua('W187KEEP = (W187KEEP or 0) + 1; local e = System.GetEntityByName("%s"); if e then pcall(System.RemoveEntity, e.id) end' % VNPC)
        live.cmd('mp_w178_trace 0'); live.cmd('mp_anim_scope_log off')
    res = {'case': 'vanilla', 'weapon': weapon, 'tag': tag, 'windups': seen, 'pressed': pressed, 'events': events[:60]}
    out = os.path.join(live.LOGS, 'run187.vanilla.%s.%s.json' % (weapon, tag))
    json.dump(res, open(out, 'w'), indent=1)
    R.stop('agent')
    print(json.dumps(res, indent=1)[:3000]); print('written', out)
    return res


