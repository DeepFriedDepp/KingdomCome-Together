def plan_opp(per, every, copy_z):
    t0 = 28.0
    p1 = t0 + per * every + 4
    p2 = p1 + per * every + 4
    end = p2 + per * every + 6
    L = plan_base(end, copy_z)
    L += ['ncombat 0 %d %s avatar:1 3 1 0 3' % (int(p1), COPY),
          'ncombat %d %d %s host 3 1 0 3' % (int(p1), int(p2), COPY),
          'ncombat %d %d %s avatar:1 3 1 0 3' % (int(p2), int(end + 30), COPY)]
    rows = [STAB_CHARGED, SLASH_Z2, SLASH_Z1]
    for k in range(per):   # phase 1: at the joiner (the host's verdict "hit" at the row's own contact)
        L.append('swingat %.1f %s local %s %d hit 6 15' % (t0 + k * every, COPY, rows[k % 3], 1233 if rows[k % 3] == STAB_CHARGED else 800))
    for k in range(per):   # phase 2: at the host's figure (rows only, no verdict on the joiner)
        L.append('row %.1f %s %s' % (p1 + 2 + k * every, COPY, rows[k % 3]))
    for k in range(per):   # phase 3: at the joiner again
        L.append('swingat %.1f %s local %s %d hit 6 15' % (p2 + 2 + k * every, COPY, rows[k % 3], 1233 if rows[k % 3] == STAB_CHARGED else 800))
    return L, end, {'phase1': [t0, p1], 'phase2_host': [p1, p2], 'phase3': [p2, end]}


