def plan_chase(secs, copy_z, speed=1.6):
    # the copy starts 9 m off along +y and closes on the joiner, who backs off along -y at speed*0.8 from t=24 (the console timer)
    t0 = 24.0
    end = t0 + secs + 6
    pts = []
    for i in range(0, int(secs) + 1):
        t = t0 + i
        py = CY - 0.8 * speed * i          # where the player is (backing off)
        cy = max(py + 2.0, CY + 9.0 - speed * i)
        pts.append('%.1f %.2f %.2f %.2f' % (t, CX, cy, copy_z))
    L = ['# WO-187 chase (generated by run187.py)', 'start 10', 'ghost %.2f %.2f %.2f 0 1 2 0.0005 30' % (CX + 8.0, CY, copy_z + 0.3), 'qmode 1 on',
         'timed %s 3.14159 %.1f %.2f %.2f %.2f %s' % (COPY, 0.0, CX, CY + 9.0, copy_z, ' '.join(pts)),
         'hands 12 %s - %s' % (COPY, SWORD), 'ncombat 0 %d %s avatar:1 3 1 0 3' % (int(end + 30), COPY)]
    if os.environ.get('W187_CHASE_SWINGS') == '1':   # B2: the chaser swings while it runs (each swing holds the copy's writer)
        k = 0
        while t0 + 2 + 2.5 * k < t0 + secs:
            L.append('row %.1f %s %s' % (t0 + 2 + 2.5 * k, COPY, (SLASH_Z2, SLASH_Z1, STAB_CHARGED)[k % 3])); k += 1
    return L, end, {'t0': t0, 'speed': speed, 'swings': os.environ.get('W187_CHASE_SWINGS') == '1'}


def native_from(off):
    with open(live.NLOG, 'rb') as f:
        f.seek(off)
        return f.read().decode('utf-8', 'replace').splitlines()


def klog_from(off):
    with open(live.KLOG, 'rb') as f:
        f.seek(off)
        return f.read().decode('utf-8', 'replace').splitlines()


def size(p):
    return os.path.getsize(p) if os.path.exists(p) else 0


def count(lines, s):
    return sum(1 for l in lines if s in l)


def scope_runs(nat, body):
    """The WO187-SCOPE lines of one body as (t_ms, action) after each move."""
    out = []
    for l in nat:
        if 'WO187-SCOPE body=%s ' % body not in l: continue
        m = re.search(r't=(\d+) action=(\S+)', l)
        if m: out.append((int(m.group(1)), m.group(2)))
    return out


def run(case, agent_dll, arg=None):
    tag = os.environ.get('W187_TAG', time.strftime('%H%M%S'))
    R.stop('agent'); R.stop('peer')
    time.sleep(5)
    z = ground(CX, CY)
    place_player(z)
    copy_z = ground(CX, CY + 1.8)
    if case == 'opp':
        L, end, info = plan_opp(int(arg or 6), 4.0, copy_z)
    elif case == 'moves':
        L, end, info = plan_moves(copy_z)
    elif case == 'figure':
        L, end, info = plan_figure(copy_z)
    elif case == 'weapon':
        L, end, info = plan_weapon(os.environ.get('W187_WEAPON', 'mace'), int(arg or 8), 4.0, copy_z)
    elif case == 'chase':
        L, end, info = plan_chase(float(arg or 30), copy_z, speed=float(os.environ.get('W187_CHASE_MPS', '1.6')))
    elif case == 'hitfb':
        L, end, info = plan_hitfb(copy_z)
    elif case == 'avplay':
        L, end, info = plan_avplay(copy_z)
    else:
        raise SystemExit('unknown case ' + case)
    plan = os.path.join(live.LOGS, 'plan.run187.%s.%s.txt' % (case, tag))
    open(plan, 'w').write('\n'.join(L) + '\n')
    noff, koff = size(live.NLOG), size(live.KLOG)
    R.peer('r187' + case + tag, plan, ['--duration', str(int(end + 20)), '--claim-host'])
    t_peer = time.time()
    R.agent('r187' + case + tag, agent_dll, ['KCDMP_TEST_JOINER_IN_WORLD=1'])
    time.sleep(12)
    live.cmd('mp_leash off')
    if case in ('moves', 'figure', 'opp', 'hitfb', 'avplay'):
        live.cmd('mp_anim_scope_log on')
    for sw in ('anim_guard', 'anim_idle', 'opp_logical', 'anim_defence', 'chase_follow'):   # W187_<SWITCH>=off: the 0.60.3 behaviour, for an A/B
        if os.environ.get('W187_' + sw.upper()) == 'off':
            live.cmd('mp_%s off' % sw)
    # the harness keeps Henry up (the engine's own damage rules untouched)
    live.lua('W187KEEP = (W187KEEP or 0) + 1; local gen = W187KEEP; local function k() if gen ~= W187KEEP then return end; '
             'if player.soul:GetState("health") < 60 then player.soul:SetState("health", 100) end; Script.SetTimer(400, k) end; k()')
    if case == 'chase':
        # the joiner backs off along -y from the plan's t0 (stream time = peer start + 10 s start delay)
        sp = info['speed'] * 0.8
        live.lua('W187CH = (W187CH or 0) + 1; local gen = W187CH; local t0 = nil; local x, y, zz = %f, %f, %f; '
                 'local function s() if gen ~= W187CH then return end; t0 = t0 or System.GetCurrTime(); local dt = System.GetCurrTime() - t0; if dt > %f then return end; '
                 'player:SetWorldPos({x = x, y = y - %f * dt, z = zz + 0.05}); Script.SetTimer(50, s) end; '
                 'Script.SetTimer(%d, s)' % (CX, CY, z, float(arg or 30), sp, int((10 + info['t0'] - (time.time() - t_peer)) * 1000)))
    deadline = t_peer + 10 + end + 6
    last_probe = 0
    while time.time() < deadline:
        time.sleep(0.5)
        if case == 'moves' and time.time() - last_probe >= 1.7:   # the copy's combat model (cm = CombatMode) between its moves
            last_probe = time.time()
            live.cmd('mp_w163_probe model %s' % COPY)
    live.cmd('mp_w187_status'); live.cmd('mp_w178_status')
    time.sleep(4)
    live.lua('W187KEEP = (W187KEEP or 0) + 1; W187CH = (W187CH or 0) + 1')
    live.cmd('mp_anim_scope_log off')
    for sw in ('anim_guard', 'anim_idle', 'opp_logical', 'anim_defence', 'chase_follow'):
        if os.environ.get('W187_' + sw.upper()) == 'off':
            live.cmd('mp_%s on' % sw)
    nat = native_from(noff)
    kl = klog_from(koff)
    st = R.load_state()
    ag = open(st['agentlog'], encoding='utf-8', errors='replace').read().splitlines() if st.get('agentlog') else []
    res = {'case': case, 'tag': tag, 'info': info}
    res['opp_lines'] = [l.strip()[15:240] for l in nat if 'WO187-OPP' in l][:40]
    res['opp_applied'] = count(nat, 'WO187-OPP npc=%s was=' % COPY)
    res['windup_held'] = count(nat, 'windup=held')
    res['windup_overwritten'] = count(nat, 'windup=overwritten')
    res['plan_planned'] = sum(1 for l in nat if 'WO187-PLAN' in l and re.search(r'planned=[1-9]', l))
    res['plan_refused'] = sum(1 for l in nat if 'WO187-PLAN' in l and 'refused=1' in l)
    res['plan_not_me'] = count(nat, 'opponent=NOT-the-local-player')
    res['pb_slots'] = sum(1 for l in kl if 'Perfect' in l and 'Slot started' in l)
    res['block_slots'] = sum(1 for l in kl if 'Block Slot started' in l and 'Perfect' not in l)
    res['queue_overflow'] = sum(1 for l in kl if 'too many actions' in l.lower())
    res['guard_holds'] = [l.strip()[15:200] for l in nat if 'WO187-GUARD' in l][:6]
    res['idle'] = [l.strip()[15:220] for l in nat if 'WO187-IDLE' in l][:10]
    res['scope_copy'] = scope_runs(nat, COPY)[:120]
    figs = sorted(set(re.search(r'body=(kcd2mp_\d+)', l).group(1) for l in nat if 'WO187-SCOPE body=kcd2mp_' in l))
    res['scope_figure'] = {f: scope_runs(nat, f)[:120] for f in figs}
    res['defence_rows'] = [l[:220] for l in ag if 'dispatch=native-defence' in l][:12]
    res['swings_recv'] = [l[:200] for l in ag if l.startswith('MP-SWING hop=recv')][:12]
    res['swing_fail'] = [l[:200] for l in ag if 'did not apply' in l][:6]
    res['fightpos'] = [l[:400] for l in ag if 'WO187-FIGHTPOS' in l][:60]
    res['w187_stats'] = [l[:1200] for l in ag if l.startswith('MP-W187-STATS')][-1:]
    res['wo166_native'] = [l[:900] for l in ag if 'windups=' in l][-1:]
    res['opp_agent'] = [l[:200] for l in ag if l.startswith('MP-W187 opponent')][:10]
    if case == 'weapon':   # per swing: the copy's wind-up (WO178-COPYSTATE) to its blade's contact here (WO166-LOCALHIT), and the shield's window
        wind = [(l[1:13], l) for l in nat if 'WO178-COPYSTATE npc=%s wind-up' % COPY in l]
        hits_ = [l[1:13] for l in nat if 'WO166-LOCALHIT dropped' in l]
        def secs(hms): h, m_, rest = hms.split(':'); return int(h) * 3600 + int(m_) * 60 + float(rest)
        pairs = []
        for ts, l in wind:
            t = secs(ts)
            nxt = [secs(h) - t for h in hits_ if 0 < secs(h) - t < 2.5]
            cd = re.search(r'countdown=set:([0-9.]+)s', l)
            pairs.append({'countdown_s': float(cd.group(1)) if cd else None, 'blade_contact_s': round(min(nxt), 3) if nxt else None})
        res['swings'] = pairs
        res['pb_windows'] = [l.strip()[:160] for l in kl if 'Perfect' in l and 'Slot started' in l][:12]
        res['timing_lines'] = [l.strip()[15:260] for l in nat if 'WO187-TIMING' in l][:4]
    if case in ('hitfb', 'avplay'):   # C1: every reaction row in, what played, and the stand-ins
        res['hit_rows'] = [l[:260] for l in ag if 'kind=NpcHit' in l or 'kind=AvatarHit' in l][:24]
        res['hit_fallback'] = [l[:300] for l in ag if 'WO187-HITFALLBACK' in l][:16]
    res['copy_combat_mode'] = [int(m.group(1)) for l in ag if l.startswith('WO163-MODEL npc=%s ' % COPY) for m in [re.search(r' cm=([0-9]+)', l)] if m]
    res['engage'] = [l[:220] for l in ag if 'MP-W132 engage' in l or 'MP-W187 engage' in l][:6]
