"""WO-178 C1b live harness (never shipped; no input sent): do hostile bandits attack the partner's figure on the host?

Host role (the agent as host, a synthetic joiner peer): the joiner's figure stands beside a bandit camp on autosave360 (its bandits
are the host's own, AI running); Henry waits <henry_m> m away so the bandits have the figure to pick. Counts the bandits' blows on the
figure (WO132-HITS npc hit on avatar), the skirmish lines naming the figure and the bandits' distances to it.

usage:  python c1b178.py <agent.dll> [seconds] [henry_m]
        W178_NEAR_HENRY=1: WO-177's scenes -- Henry stays where the save has him, the figure 2.5 m east; every fighter turning on it counted
Writes logs/c1b178.json.
"""
import json, math, os, re, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import live
import run165 as R
import run176 as B

AX, AY = 2782.0, 2592.0   # beside the Kaspar camp's bandits on autosave360 (tapo_kasparBandit_2 and _5 ~8 m away)


def bandits():
    live.lua('local t=System.GetEntitiesInSphere({x=%f,y=%f,z=100}, 120); local s=""; for _,e in ipairs(t) do local n=e:GetName(); '
             'if string.find(string.lower(n),"bandit") then local p=e:GetWorldPos(); local hp=-1; pcall(function() hp=e.soul:GetState("health") end); '
             's=s..string.format("%%s,%%.1f,%%.1f,%%.0f ",n,p.x,p.y,hp) end end; System.LogAlways("[W178B] "..s)' % (AX, AY))
    time.sleep(0.5)
    out = []
    for l in reversed(live.tail(live.KLOG, 40, r'\[W178B\]')):
        for tok in l.split('[W178B] ')[1].split():
            n, x, y, hp = tok.split(',')
            out.append((n, float(x), float(y), float(hp)))
        break
    return out


def henry_pos():
    live.lua('local p=player:GetWorldPos(); System.LogAlways(string.format("[W178H] %.2f %.2f %.2f", p.x, p.y, p.z))')
    time.sleep(0.5)
    for l in reversed(live.tail(live.KLOG, 30, r'\[W178H\]')):
        x, y, z = l.split('[W178H] ')[1].split()[:3]
        return float(x), float(y), float(z)
    return None


def run(agent_dll, seconds=60, henry_m=45.0, near_henry=False):
    global AX, AY
    R.stop('agent'); R.stop('peer')
    time.sleep(3)
    if near_henry:   # WO-177's scenes (the meadow fight, the village brawl): Henry stays where the save has him, the figure 2.5 m east
        hp = henry_pos()
        AX, AY = hp[0] + 2.5, hp[1]
    else:
        hz2 = B.ground(AX - henry_m, AY - henry_m)
        for _ in range(2):
            live.lua('player:SetWorldPos({x=%f, y=%f, z=%f})' % (AX - henry_m, AY - henry_m, (hz2 or 108.0) + 0.3)); time.sleep(1.0)
    b0 = bandits()
    gx, gy = AX, AY
    gz = B.ground(gx, gy) or 108.7
    total = 10 + seconds + 10
    L = ['# WO-178 C1b (generated by c1b178.py): host role; the synthetic joiner figure beside the bandit camp', 'start 3',
         'ghost %.2f %.2f %.2f 0 1 50 0.0005 30' % (gx, gy, gz), 'gcombat 5 %d 1' % total]
    plan = os.path.join(live.LOGS, 'plan.c1b178.txt')
    open(plan, 'w').write('\n'.join(L) + '\n')
    n0 = B.nlen()
    with open(live.KLOG, 'rb') as f:
        f.seek(0, 2); k0 = f.tell()
    R.agent('c1b178', agent_dll, [])   # first: the agent claims the host
    time.sleep(14)
    R.peer('c1b178', plan, ['--duration', str(int(total + 10))])
    time.sleep(6)
    samples = []
    t_end = time.time() + seconds
    while time.time() < t_end:
        if os.environ.get('W178_PH') == '1':   # experiment: each bandit personally hostile to the figure (the game's own pair hostility)
            live.lua('local t=System.GetEntitiesInSphere({x=%f,y=%f,z=100}, 60); local f=nil; for _,e in ipairs(t) do local n=e:GetName(); '
                     'if n:find("^kcd2mp_%%d+$") then f=e end end; if f then for _,e in ipairs(t) do if string.find(string.lower(e:GetName()),"bandit") then '
                     'pcall(function() AI.AddPersonallyHostile(e.id, f.id) end) end end end' % (gx, gy))
        bs = bandits()
        samples.append([(n, round(math.hypot(x - gx, y - gy), 1), hp) for n, x, y, hp in bs])
        time.sleep(5)
    nat = B.nlines_from(n0)
    with open(live.KLOG, 'rb') as f:
        f.seek(k0); kl = f.read().decode('utf-8', 'replace').splitlines()
    res = {'bandits_at_start': [(n, round(math.hypot(x - gx, y - gy), 1), hp) for n, x, y, hp in b0],
           'bandit_blows_on_figure': sum('WO132-HITS npc hit on avatar' in l for l in nat),
           'figure_hit_lines': [l.strip()[15:230] for l in nat if 'hit on avatar' in l][:6],
           'skirmish_figure': [l.strip()[:200] for l in kl if 'kcd2mp' in l and ('Skirmish' in l or 'target' in l.lower() or 'Opponent' in l)][:12],
           'opponent_changes': [l.strip()[:200] for l in kl if 'Opponent change' in l][:12],
           'attack_targets': {},
           'samples': samples[::3]}
    res['figure_targeted_by'] = {}
    res['figure_soul_added'] = sum('SoulAdded on kcd2mp' in l for l in kl)
    res['figure_removed'] = sum("Removing skirmish soul 'kcd2mp" in l for l in kl)
    res['skirmish_events'] = sum('Skirmish event:' in l for l in kl)
    for l in kl:   # any fighter turning on the figure (WO-177's count): '... (target kcd2mp_N)'
        m = re.search(r'Skirmish event: (\w+) on (\S+) \(target (kcd2mp_\d+)\)', l)
        if m: res['figure_targeted_by'][m.group(2)] = res['figure_targeted_by'].get(m.group(2), 0) + 1
    for l in kl:   # the engine's own skirmish attacks: 'Skirmish event: Attack on <attacker> (target <victim>)'
        m = re.search(r'Skirmish event: Attack on (\S+) \(target ([^)]*)\)', l)
        if m and ('andit' in m.group(1) or near_henry):
            k = 'figure' if 'kcd2mp' in m.group(2) else ('henry' if m.group(2) == 'Dude' else m.group(2))
            res['attack_targets'][k] = res['attack_targets'].get(k, 0) + 1
    json.dump(res, open(os.path.join(live.LOGS, 'c1b178.json'), 'w'), indent=1)
    R.stop('agent'); R.stop('peer')
    print(json.dumps(res, indent=1))
    return res


if __name__ == '__main__':
    a = sys.argv
    run(a[1], int(a[2]) if len(a) > 2 else 60, float(a[3]) if len(a) > 3 else 45.0, near_henry=os.environ.get('W178_NEAR_HENRY') == '1')
