"""WO-190 live harness (never shipped): the animation-parity scenarios. Unattended: no focus change, no key press; the throwaway playline4
only. The Modding Tools game is the JOINER of a synthetic host through a local relay (run165.py: relay, peer, agent, stop); run187.py's plans.

usage (W190_SP = the session's rig folder holding run/agent and run/relay; KCD2MP_INSTALL = the Modding Tools folder):
  python run190.py <scenario> <before|after>
    before = every WO-190 switch off (the 0.60.7 behaviour; the trace itself is this build's), after = the defaults (on)
  scenarios:
    figwalk    locomotion, the figure: the partner walks a 12 m line back and forth (1.4 m/s); half the run his stream has 350 ms spikes
    copywalk   locomotion, a copy: the host's NPC walks 4 s / stands 3 s on a line; spikes as above
    figfight   combat, the figure: 8 moves of the partner (hook, kick, block, punch, dodge ...) in combat (run187 plan_figure)
    fighits    hit reactions, the figure: 8 of the partner's reaction rows, 4 of them another weapon's (run187 plan_avplay)
    copyfight  combat, a copy fighting the host's figure: 10 moves, the guard between them (run187 plan_moves; A5)
    copyhits   hit reactions, a copy: 8 host reaction rows, 6 another weapon's or actor class's (run187 plan_hitfb)
    copyduel   A6: the host NPC's reaction row, then its next swing at me 0.5-0.9 s later, 8 times (the copy still in 0x20 / 0x40)
    opp        A7: the copy fights me, then the host's figure, then me (6 swings each): engage holds, shield windows (WO-187: 12 of 12)
    fighitsarmed  as fighits, the figure holding a sword (A1: never a bare-handed stand-in on an armed figure)
    auto       copyfight with mp_anim_trace OFF: mp_anim_scope_log auto traces the fight's bodies only (A9)
    night      A2: hour 22, the copy fights me with the host's sword (never the torch)
    fps        the frame-rate check: the town's copies held, the WO-190 switches on / off / on, the DLL's FRAME lines
    town       A3: every NPC within 30 m held at its spot by the host's stream for 60 s (idle and sitting copies); the overflows
    townbase   A3's baseline: the same 60 s with no agent (the game's own NPCs, no copies)
    clinch     A8: a village copy fighting me gets the host NPC's clinch rows (sync): the plain fallback must fire
Results: <W190_SP>/results/<scenario>.<mode>.json; the native lines of the run in <W190_SP>/results/<scenario>.<mode>.native.log.
"""
