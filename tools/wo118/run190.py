def say(*a): print(time.strftime('%H:%M:%S'), *a, flush=True)


def size(p): return os.path.getsize(p) if os.path.exists(p) else 0


def read_from(path, off):
    with open(path, 'rb') as f:
        f.seek(off); return f.read().decode('utf-8', 'replace').splitlines()


def set_mode(mode):
    for sw in SWITCHES:
        live.cmd('%s %s' % (sw, 'off' if mode == 'before' else 'on'))
        time.sleep(0.05)
    live.cmd('mp_sync_fallback %s' % ('off' if mode == 'before' else 'on'))


def keep_up():
    live.lua('W187KEEP = (W187KEEP or 0) + 1; local gen = W187KEEP; local function k() if gen ~= W187KEEP then return end; '
             'if player.soul:GetState("health") < 60 then player.soul:SetState("health", 100) end; Script.SetTimer(400, k) end; k()')


def plan_figwalk(z):
    # the figure walks a 12 m line along +x at 1.4 m/s, ping-pong (a turn every ~8.6 s), 30 ms samples (a real partner's cadence)
    end = 70.0
    L = ['# WO-190 figwalk (generated by run190.py)', 'start 6', 'ghost %.2f %.2f %.2f 1 0 12 1.4 30' % (CX - 6.0, CY + 4.0, z + 0.3), 'qmode 1 on']
    return L, end, {'speed': 1.4}


def plan_copywalk(z):
    # the copy walks 4 s / stands 3 s along +x on a 5.6 m leg, back and forth
    t, x, k, pts = 0.0, CX - 3.0, 0, []
    pts.append('%.1f %.2f %.2f %.2f' % (t, x, CY + 3.0, z))
    stops = []
    while t < 66.0:
        d = 1 if k % 2 == 0 else -1
        x2 = x + d * 5.6
        pts.append('%.1f %.2f %.2f %.2f' % (t + 4.0, x2, CY + 3.0, z)); stops.append(t + 4.0)
        pts.append('%.1f %.2f %.2f %.2f' % (t + 7.0, x2, CY + 3.0, z))
        t += 7.0; x = x2; k += 1
    end = t + 2
    L = ['# WO-190 copywalk (generated by run190.py)', 'start 10', 'ghost %.2f %.2f %.2f 0 1 2 0.0005 30' % (CX + 8.0, CY - 4.0, z + 0.3), 'qmode 1 on',
         'timed %s 1.5708 %s' % (COPY, ' '.join(pts)), 'hands 12 %s - %s' % (COPY, P.SWORD)]
    return L, end, {'stops': stops}


def plan_copyduel(z):
    # A6: each round, the host NPC's own reaction row (it took a blow on the host) and then its next swing at me 0.5-0.9 s later
    rows = [(P.SLASH_Z2, 800), (P.SLASH_Z1, 767), (P.STAB_CHARGED, 1233)]
    t0, every = 28.0, 3.2
    n = 8
    end = t0 + n * every + 6
    L = P.plan_base(end, z, dist=1.6)
    L = [l for l in L if not l.startswith('hands ')] + ['hands 12 %s - %s' % (COPY, P.SWORD), 'ncombat 0 %d %s avatar:1 3 1 0 3' % (int(end + 30), COPY),
                                                       'row 24 %s %s' % (COPY, P.SLASH_Z2)]
    gaps = []
    for k in range(n):
        tr = t0 + k * every
        gap = 0.5 + 0.1 * (k % 5)
        L.append('react %.1f %s %s' % (tr, COPY, P.HIT_LS_Z2))
        g, lag = rows[k % 3]
        L.append('swingat %.2f %s local %s %d hit 6 15' % (tr + gap, COPY, g, lag))
        gaps.append(gap)
    return L, end, {'swings': n, 'gaps': gaps}


def plan_clinch(z, villager, vx, vy, vz):
    t0, every = 26.0, 4.0
    seq = [CLINCH_PUNCH, CLINCH_THROW] * 3
    end = t0 + len(seq) * every + 6
    L = ['# WO-190 clinch (generated by run190.py)', 'start 6', 'ghost %.2f %.2f %.2f 0 1 2 0.0005 30' % (CX + 8.0, CY, z + 0.3), 'qmode 1 on',
         'hold %s %.2f %.2f %.2f 3.14159' % (villager, vx, vy, vz), 'ncombat 0 %d %s avatar:1 3 1 0 3' % (int(end + 30), villager)]
    for k, g in enumerate(seq):
        L.append('row %.1f %s %s' % (t0 + k * every, villager, g))
    return L, end, {'rows': len(seq)}


def town_npcs(radius=30.0):
    tok = 'W190T%d' % int(time.time() * 1000)
    off = size(live.KLOG)
    live.lua('local p = player:GetWorldPos(); local n = 0; for _, e in ipairs(System.GetEntitiesInSphere(p, %f) or {}) do '
             'if e.actor and e.class == "NPC" and e.GetName and not string.find(e:GetName(), "kcd2mp_") then local q = e:GetWorldPos(); '
             'local a = e:GetWorldAngles(); System.LogAlways(string.format("[%s] %%s %%.2f %%.2f %%.2f %%.3f", e:GetName(), q.x, q.y, q.z, a.z)); n = n + 1 end end' % (radius, tok))
    time.sleep(1.0)
    out = []
    for l in read_from(live.KLOG, off):
        m = re.search(r'\[%s\] (\S+) (-?[0-9.]+) (-?[0-9.]+) (-?[0-9.]+) (-?[0-9.]+)' % tok, l)
        if m: out.append((m.group(1), float(m.group(2)), float(m.group(3)), float(m.group(4)), float(m.group(5))))
    return out


def anim_lines(nat):
    out = []
    for l in nat:
        if 'WO190-ANIM utc=' not in l: continue
        m = re.search(r'utc=(\d+) body=(\S+) role=(\S+) scope=(\S+) action=(\S+) frag=(\d+) prio=(-?\d+) flags=0x([0-9A-F]+) was=(\S+) held_ms=(-?[0-9.]+) tags=(\S+) spd=(-?[0-9.]+) age_ms=(-?[0-9.]+) fight=(\d)', l)
        if m:
            out.append({'utc': int(m.group(1)), 'body': m.group(2), 'role': m.group(3), 'scope': m.group(4), 'action': m.group(5), 'frag': int(m.group(6)),
                        'prio': int(m.group(7)), 'flags': int(m.group(8), 16), 'was': m.group(9), 'held_ms': float(m.group(10)), 'tags': m.group(11),
                        'spd': float(m.group(12)), 'age_ms': float(m.group(13)), 'fight': int(m.group(14))})
    return out


def status_line(ag, tag):
    l = [x for x in ag if x.startswith(tag)]
    return l[-1] if l else ''


def loco(stat):
    m1 = re.search(r'loco_fig=(\d+)/(\d+)/(\d+)/(\d+)', stat)
    m2 = re.search(r'loco_copy=(\d+)/(\d+)/(\d+)/(\d+)', stat)
    return ([int(x) for x in m1.groups()] if m1 else None, [int(x) for x in m2.groups()] if m2 else None)


def fps_ab(z, secs=60):
    """The frame-rate regression check (mp_anim_trace off): the town's copies held by the host's stream (every NPC within 30 m) and the
    partner's figure walking, three phases -- the WO-190 switches on, off (the 0.60.7 code paths), on -- the DLL's FRAME fps and its own cost."""
    npcs = town_npcs(30.0)
    end = 3 * secs + 20.0
    L = ['# WO-190 fps (generated by run190.py)', 'start 6', 'ghost %.2f %.2f %.2f 1 0 12 1.4 30' % (CX - 6.0, CY + 4.0, z + 0.3), 'qmode 1 on']
    for (n, x, y, zz, yaw) in npcs[:40]:
        L.append('hold %s %.2f %.2f %.2f %.3f' % (n, x, y, zz, yaw))
    plan = os.path.join(live.LOGS, 'plan.run190.fps.txt')
    open(plan, 'w').write('\n'.join(L) + '\n')
    R.peer('r190fps', plan, ['--duration', str(int(end + 20)), '--claim-host'])
    R.agent('r190fps', AGENT, ['KCDMP_TEST_JOINER_IN_WORLD=1'])
    time.sleep(16)
    live.cmd('mp_leash off'); live.cmd('mp_anim_trace off'); live.cmd('mp_anim_scope_log auto')
    out = {}
    for phase, mode in (('on', 'after'), ('off', 'before'), ('on2', 'after')):
        set_mode(mode)
        time.sleep(5)
        off = size(live.NLOG)
        time.sleep(secs)
        frames = [l for l in read_from(live.NLOG, off) if 'FRAME ' in l and 'fps=' in l]
        vals = [(float(re.search(r'fps=([0-9.]+)', l).group(1)), int(re.search(r'ours_us_mean=([0-9]+)', l).group(1))) for l in frames
                if re.search(r'ours_us_mean=([0-9]+)', l)]
        out[phase] = {'windows': len(vals), 'fps': [v[0] for v in vals], 'ours_us_mean': [v[1] for v in vals]}
        say('fps phase', phase, out[phase])
    on = [f for k in ('on', 'on2') for f in out[k]['fps']]
    offv = out['off']['fps']
    ratio = (sum(on) / len(on)) / (sum(offv) / len(offv)) if on and offv else None
    res = {'scenario': 'fps', 'copies': len(npcs[:40]), 'phases': out, 'fps_ratio_on_off': round(ratio, 3) if ratio else None,
           'pass': ratio is not None and ratio >= 0.9}
    json.dump(res, open(os.path.join(OUT, 'fps.ab.json'), 'w'), indent=1)
    R.stop('agent'); R.stop('peer')
    print(json.dumps(res, indent=1))
    return res


def run(scen, mode):
    tag = '%s.%s' % (scen, mode)
    say('== WO-190', tag)
    R.stop('agent'); R.stop('peer')
    time.sleep(5)
    R.relay(RELAY)
    z = P.ground(CX, CY)
    P.place_player(z)
    copy_z = P.ground(CX, CY + 1.8)
    peer_opts = ['--claim-host']
    info = {}
    if scen == 'townbase':
        live.cmd('mp_anim_trace off')
        koff = size(live.KLOG)
        time.sleep(60)
        kl = read_from(live.KLOG, koff)
        ov = [l for l in kl if 'Animation-queue overflow' in l]
        by = {}
        for l in ov:
            m = re.search(r'CharInst: [0-9A-F]+ / ([^.]+)\.', l)
            if m: by[m.group(1)] = by.get(m.group(1), 0) + 1
        res = {'scenario': scen, 'mode': mode, 'overflows': len(ov), 'by_body': dict(sorted(by.items(), key=lambda x: -x[1])[:12]), 'secs': 60}
        json.dump(res, open(os.path.join(OUT, tag + '.json'), 'w'), indent=1)
        print(json.dumps(res, indent=1))
        return res
    if scen == 'fps':
        return fps_ab(z, int(os.environ.get('W190_FPS_S', '125')))
    if scen == 'figwalk':
        L, end, info = plan_figwalk(z)
    elif scen == 'copywalk':
        L, end, info = plan_copywalk(copy_z)
    elif scen == 'figfight':
        L, end, info = P.plan_figure(copy_z)
    elif scen in ('fighits', 'fighitsarmed'):
        L, end, info = P.plan_avplay(copy_z)
    elif scen == 'copyfight':
        L, end, info = P.plan_moves(copy_z)
    elif scen == 'opp':   # A7 + WO-187's shield windows: the copy fights me, then the host's figure, then me again (6 swings a phase)
        L, end, info = P.plan_opp(6, 4.0, copy_z)
    elif scen == 'copyhits':
        L, end, info = P.plan_hitfb(copy_z)
    elif scen == 'copyduel':
        L, end, info = plan_copyduel(copy_z)
    elif scen == 'clinch':
        vx, vy = CX, CY + float(os.environ.get('W190_CLINCH_DIST', '0.7'))   # inside the unarmed sync distance (0.8 m): the engine asks the gate
        vz = P.ground(vx, vy)
        L, end, info = plan_clinch(z, VILLAGER, vx, vy, vz)
    elif scen in ('night', 'auto'):
        # night (A2): hour 22 -- the copy of a host NPC fighting me keeps the host's sword (never the night routine's torch); 8 swings at me
        # auto (A9): the copy fighting the host's figure with mp_anim_trace OFF: the default scope log (auto) traces the fight's bodies only
        if scen == 'night':
            live.lua('Calendar.SetWorldTime(Calendar.GetWorldTime() + 14 * 3600)')
            time.sleep(2)
            L, end, info = P.plan_weapon('sword', 8, 3.0, copy_z)
        else:
            L, end, info = P.plan_moves(copy_z)
    elif scen in ('town', 'townwalk'):
        npcs = town_npcs(30.0)
        end = 75.0
        L = ['# WO-190 town (generated by run190.py)', 'start 6', 'ghost %.2f %.2f %.2f 0 1 2 0.0005 30' % (CX + 8.0, CY, z + 0.3), 'qmode 1 on']
        for (n, x, y, zz, yaw) in npcs[:40]:
            L.append('hold %s %.2f %.2f %.2f %.3f' % (n, x, y, zz, yaw))
        info = {'npcs': [n[0] for n in npcs[:40]]}
    else:
        raise SystemExit('unknown scenario ' + scen)
    spikes = scen in ('figwalk', 'copywalk')
    if spikes:   # the second half of the run: 350 ms spikes on 12 % of the samples (the field's short gaps)
        peer_opts += ['--spike-ms', '350', '--spike-pct', '12', '--seed', '190']
    plan = os.path.join(live.LOGS, 'plan.run190.%s.txt' % tag)
    open(plan, 'w').write('\n'.join(L) + '\n')
    set_mode(mode)   # the Lua halves now (the agent's and the DLL's after it connects)
    noff, koff = size(live.NLOG), size(live.KLOG)
    R.peer('r190' + tag, plan, ['--duration', str(int(end + 20))] + peer_opts)
    t_peer = time.time()
    R.agent('r190' + tag, AGENT, ['KCDMP_TEST_JOINER_IN_WORLD=1'])
    time.sleep(12)
    live.cmd('mp_leash off')
    set_mode(mode)
    live.cmd('mp_anim_trace %s' % ('off' if scen == 'auto' else 'on'))
    if scen == 'auto': live.cmd('mp_anim_scope_log auto')
    live.cmd('mp_w190_status')   # the counters at the start (they count since the DLL loaded)
    keep_up()
    if scen == 'townwalk':   # the player walks a 6 m circle through the held copies (console moves, no input): their look IK tracks him
        live.lua('W190TW = (W190TW or 0) + 1; local gen = W190TW; local t0 = nil; local p0 = player:GetWorldPos(); '
                 'local function s() if gen ~= W190TW then return end; t0 = t0 or System.GetCurrTime(); local a = (System.GetCurrTime() - t0) * 0.2; '
                 'local x, y = p0.x + 6 * math.cos(a) - 6, p0.y + 6 * math.sin(a); local z = System.GetTerrainElevation({x=x, y=y, z=0}) or p0.z; '
                 'player:SetWorldPos({x = x, y = y, z = z + 0.05}); Script.SetTimer(50, s) end; s()')
    if scen == 'fighitsarmed':   # A1: the partner's figure holds a sword and a shield here (as a partner who fights armed): its reactions
        arm = ('local e = System.GetEntityByName("kcd2mp_0"); if e and e.inventory and e.human then '
               'for _, c in ipairs({"%s", "%s"}) do pcall(function() e.inventory:CreateItem(c, 1, 1) end); '
               'local ok, id = pcall(function() return e.inventory:FindItem(c) end); if ok and id then pcall(function() e.human:DrawFromInventory(id, 0, true) end) end end; '
               'System.LogAlways("[W190A] figure armed") end' % (P.SWORD, SHIELD))
        for _ in range(3):
            live.lua(arm); time.sleep(1.5)
    deadline = t_peer + 10 + end + 4
    while time.time() < deadline:
        time.sleep(0.5)
    live.cmd('mp_w190_status'); live.cmd('mp_w187_status'); live.cmd('mp_w178_status')
    time.sleep(4)
    live.lua('W187KEEP = (W187KEEP or 0) + 1; W190TW = (W190TW or 0) + 1')
    live.cmd('mp_anim_trace off')
    nat = read_from(live.NLOG, noff)
    kl = read_from(live.KLOG, koff)
    st = R.load_state()
    ag = open(st['agentlog'], encoding='utf-8', errors='replace').read().splitlines() if st.get('agentlog') else []
    open(os.path.join(OUT, tag + '.native.log'), 'w', encoding='utf-8').write('\n'.join(nat))
    open(os.path.join(OUT, tag + '.agent.log'), 'w', encoding='utf-8').write('\n'.join(ag))
    peerlog = st.get('peerlog')
    if peerlog and os.path.exists(peerlog):
        open(os.path.join(OUT, tag + '.peer.log'), 'w', encoding='utf-8').write(open(peerlog, encoding='utf-8', errors='replace').read())
    ov = [l for l in kl if 'Animation-queue overflow' in l]
    by = {}
    for l in ov:
        m = re.search(r'CharInst: [0-9A-F]+ / ([^.]+)\.', l)
        if m: by[m.group(1)] = by.get(m.group(1), 0) + 1
    w190 = status_line(ag, 'MP-W190-STATS')
    w190s = [x for x in ag if x.startswith('MP-W190-STATS')]
    lo0, lo1 = loco(w190s[0]) if w190s else (None, None), loco(w190)
    loco_run = [[b - a for a, b in zip(lo0[i], lo1[i])] if lo0[i] and lo1[i] else None for i in (0, 1)]
    res = {'scenario': scen, 'mode': mode, 'info': info, 'overflows': len(ov), 'overflow_by_body': dict(sorted(by.items(), key=lambda x: -x[1])[:12]),
           'too_many_actions': sum(1 for l in kl if 'too many actions' in l.lower()), 'w190_stats': w190[:1500], 'loco': loco_run, 'loco_total': loco(w190),
           'w187_stats': status_line(ag, 'MP-W187-STATS')[:900], 'anim_lines': sum(1 for l in nat if 'WO190-ANIM utc=' in l),
           'idle': [l.strip()[15:220] for l in nat if 'WO190-IDLE' in l or 'WO187-IDLE' in l][:12],
           'takeover': [l.strip()[15:240] for l in nat if 'WO190-TAKEOVER' in l][:12],
           'refused_state': [l.strip()[15:200] for l in nat if 'refused: the copy' in l][:12],
           'windups': sum(1 for l in nat if 'WO178-COPYSTATE npc=' in l and 'wind-up state' in l),
           'pb_slots': sum(1 for l in kl if 'Perfect' in l and 'Slot started' in l),
           'hitfallback': [l[:300] for l in ag if 'WO187-HITFALLBACK' in l][:12],
           'syncfallback': [l[:260] for l in ag if 'WO167-SYNCFALLBACK' in l or 'WO190-CLINCH' in l][:12],
           'clinch_native': [l.strip()[15:200] for l in nat if 'WO178-CLINCH' in l][:6],
           'rows_in': [l[:240] for l in ag if 'section=inbound' in l and ('kind=NpcAttack' in l or 'kind=NpcHit' in l or 'kind=AvatarHit' in l)][:24],
           'shown': [l[:220] for l in ag if 'WO167-SHOWN' in l][:12],
           'torch': [l for l in kl if 'WO190-TORCH' in l][:6], 'look': sum(1 for l in kl if 'WO190-LOOK' in l),
           'engage': [l[:220] for l in ag if 'MP-W132 engage' in l or 'MP-W190 engage' in l][:12],
           'engage_off': sum(1 for l in ag if 'MP-W132 engage off' in l), 'engage_on': sum(1 for l in ag if 'MP-W132 engage on' in l),
           'engage_holds': sum(1 for l in ag if 'MP-W190 engage hold' in l),
           'plan_planned': sum(1 for l in nat if 'WO187-PLAN' in l and re.search(r'planned=[1-9]', l)),
           'faults': [l.strip()[15:200] for l in nat if ('FAULT' in l and 'FAULT-SUM' not in l) or 'switched OFF' in l][:10]}
    json.dump(res, open(os.path.join(OUT, tag + '.json'), 'w'), indent=1)
    R.stop('agent'); R.stop('peer')
    print(json.dumps({k: (v if not isinstance(v, list) or len(v) < 6 else v[:6] + ['...%d' % len(v)]) for k, v in res.items()}, indent=1)[:5000])
    return res


