<#
.SYNOPSIS
    WO-183: synthetic test for the playtest patch's Lua half (the landing's area check, mp_replay_blocked, the sweep that never runs mid-fight, no save request from a scene release). No game, relay or agent needed.
.DESCRIPTION
    Same driver as Test-NpcSmoothSynthetic.ps1 (the real kdcmp.lua under
    MoonSharp, engine stubbed, fake clock); scenario file
    Test-WO183Synthetic.lua. Live evidence: docs/WO-183-findings.md.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\Test-WO183Synthetic.ps1
#>
[CmdletBinding()]
param(
    [string] $KdcmpLua = '',
    [string] $MoonSharpVersion = '2.0.0.0'
)
$toolsDir = Split-Path -Parent $MyInvocation.MyCommand.Path
& (Join-Path $toolsDir 'Test-NpcSmoothSynthetic.ps1') `
    -KdcmpLua $KdcmpLua -MoonSharpVersion $MoonSharpVersion `
    -Scenario (Join-Path $toolsDir 'Test-WO183Synthetic.lua') `
    -Title 'WO-183 synthetic game-side Lua test'
exit $LASTEXITCODE
